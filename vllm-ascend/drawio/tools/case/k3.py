"""③ 案例二：TTFT 47 秒里 92% 是排队（不是算力不够）。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "③ 案例二：TTFT 47 秒，但只有 2% 是计算——先拆时间，再谈优化"
SUB = ("现象：128 并发压测，TTFT p50 <b>47 s</b>、p90 87 s；第一反应是「P 段算得太慢」。"
       "真相：<b>92% 的时间是「请求在等自己被派发」</b>，P 段真实计算只要 1.4 s，"
       "瓶颈在 D 段的输出速度。")


def build(doc: Doc) -> None:
    p = doc.page("③ 案例：TTFT 拆解", pw=1560, ph=1540)
    head(p, TITLE, SUB)
    X = 36

    # --- 拆解表 -----------------------------------------------------------
    y = 148
    p.text(X, y - 30, 1300, 22,
           "<b>第一步：把 47 秒拆成四段（这是本案例最值钱的一张表）</b>", "text_b")
    rows = [
        ["等待派发（排队）", "<b>45 s</b>", "<b>92%</b>", "系统整体服务率不足"],
        ["P 段真实计算", "1 s", "2%", "三个 chunk 各约 460 ms"],
        ["KV 导出 + 导入", "1 s", "6%", "跨机搬运"],
        ["合计", "47 s", "100%", "——"],
    ]
    table(p, X, y, [("时段", 300), ("p50", 220), ("占比", 180), ("说明", 724)], rows,
          row_h=36)
    p.box(X, y + 36 * 5 + 16, 1424, 92,
          "<font style=\"font-size:10px\">"
          "<b>这个拆解直接推翻第一反应：</b>如果「TTFT 大」就去找 P 段算力，"
          "最多只能优化那 2%（1 秒）。<br>"
          "真正的杠杆是<b>提高整条流水线的服务率</b>——而服务率被 D 段的输出速度卡住了。"
          "所以先拆时间，再决定优化谁。</font>",
          "box", "fail")

    # --- 物理上限 ---------------------------------------------------------
    y2 = y + 36 * 5 + 148
    p.text(X, y2 - 30, 1300, 22,
           "<b>第二步：算系统的物理上限（这一步能判断「是 bug 还是容量不够」）</b>",
           "text_b")
    p.box(X, y2, 1424, 120,
          "<font style=\"font-size:10px\">"
          "· D 段单请求最少要 <b>1500 token × 18.5 ms ≈ 27.8 s</b>；<br>"
          "· 能同时跑的请求数约 22 → 理论上限 <b>22 ÷ 27.8 ≈ 0.79 请求/秒</b>；<br>"
          "· 所以 128 个请求至少需要 <b>128 ÷ 0.79 ≈ 162 s</b> 才能排空——"
          "这是这套 1P(2卡)+1D(2卡) 对该负载的<b>物理上限</b>；<br>"
          "· 而实测服务率只有 <b>0.30 请求/秒</b>，<b>比上限低了 62%</b>——"
          "这部分差距不是硬件问题，而是案例一那个「图掉出」白送的。</font>",
          "box", "neutral")

    # --- 测量陷阱 ---------------------------------------------------------
    y3 = y2 + 160
    p.text(X, y3 - 30, 1300, 22,
           "<b>第三步：测量本身有三个坑（不校验会得出错 2~6 倍的数）</b>", "text_b")
    panel(p, X, y3, 460, 180, "坑一：用错了派生指标", [
        "日志里的「每秒步数」是<b>含空排的平均步间隔</b>；",
        "要算真实步时必须是 <b>10 秒 ÷ 该窗口内的步数</b>。",
        "两者能差 2~6 倍——直接用前者会把步时算小。",
    ], "fail")
    panel(p, X + 482, y3, 460, 180, "坑二：跨机时间戳不可信", [
        "边端与云端时钟不同步（实测边端快约 110 秒）；",
        "所以跨机拼接时间戳做端到端会直接错，",
        "只能用<b>同一台机器上的阶段边界</b>做差。",
    ], "fail")
    panel(p, X + 964, y3, 460, 180, "坑三：生存者偏差", [
        "128 个请求里只有 74 个完成、106 个拿到过 token；",
        "剩下 54 个「连第一个 token 都没拿到」根本不在分位数里。",
        "→ 真实 TTFT 分布被截断，<b>p50 是乐观值</b>。",
    ], "fail")

    # --- 测量方法 ---------------------------------------------------------
    y4 = y3 + 220
    p.text(X, y4 - 30, 1300, 22,
           "<b>第四步：没有端到端打点时，怎么量（用四个阶段边界做差）</b>",
           "text_b")
    p.box(X, y4, 1424, 96,
          "<font style=\"font-size:10px\">"
          "P 侧收到请求 → D 侧接纳 → D 侧就绪 → 完成，四个时刻各有一条日志；"
          "因为本负载所有请求的输出长度恒为 1500，"
          "所以 <b>TPOT = （完成 − 就绪）÷ 1499</b> 就是干净的，不受 prompt 长度差异影响。<br>"
          "<font color=\"#c0392b\">前提：P/D 在同一台机器上（本案例确实如此）；"
          "跨机时必须先校准时钟，否则这个减法没有意义。</font></font>",
          "box", "cloudd")

    # --- 根因与修复 -------------------------------------------------------
    y5 = y4 + 136
    p.box(X, y5, 1424, 108,
          "<b>第五步：根因是「双重的」，必须分开说</b><br>"
          "<font style=\"font-size:10px\">"
          "① <b>TTFT 主因 = 容量不足</b>（物理上限 0.79，实测 0.30）→ 优化方向是提服务率，不是加 P 算力；<br>"
          "② <b>TPOT 主因 = 配置 bug</b>（案例一那个图掉出，把服务率从 0.79 打到 0.30）→ "
          "改一个桶列表就能回收 62%；<br>"
          "③ 其余次要项：KV 导入排队、首 token 独占一个调度窗口、三个 chunk 三次跨机握手、空转抢 CPU。<br>"
          "<font color=\"#c0392b\">报告里必须这样分开写，否则「加机器」和「改配置」会被混为一谈。</font></font>",
          "box", "data")

    y6 = y5 + 148
    bridge(p, y6, "本页交接：本案例的结论依赖「图确实掉出了」这个推断。下一步（④）看一个"
                  "「指标明明在、但全都是零」的案例——它教会我们「零有几种含义」。")

    y7 = y6 + 76
    anchors(p, y7, [
        "复盘原文：pds_comm_ww_TTFT_TPOT_劣化分析.md（四段拆解 :57-73、生存者偏差 :79-83、"
        "服务率与物理上限 :87-115、测量口径校验 :49-53、时钟不同步 :4、修复表 :249-266）",
        "「每步只算 1+K 个 query」的背景：见 MTP 套 ⑦；图掉出机制见本套 ②",
        "服务率与并发的关系：见「进程与线程」套 ⑪⑫（调度器每步挑一批）",
    ], h=104)

    y8 = y7 + 136
    concl(p, y8,
          "<b>一句话记住这个案例：</b>面对「延迟大」，第一步永远是<b>把时间拆开</b>——"
          "排队、计算、传输各占多少；第二步是<b>算物理上限</b>，判断差距是「硬件不够」还是「配置白送」；"
          "<b>第三步才是优化。</b>")

    legend(p, y8 + 92)

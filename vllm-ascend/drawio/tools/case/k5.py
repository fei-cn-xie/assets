"""⑤ 案例四：级联故障——一个请求放不下，最后整个集群挂住。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "⑤ 案例四：从「一个请求放不下」到「整个集群挂住」的四级级联"
SUB = ("现象：请求无限期挂起（ttl 1800 s），edge 与 prefill 都在空转、不报错。"
       "真相：<b>decode 引擎早就死了</b>——第一个 fatal 发生在几分钟前；"
       "后面看到的「卡死」是三个独立缺陷串成的级联。")


def build(doc: Doc) -> None:
    p = doc.page("⑤ 案例：级联故障", pw=1560, ph=1580)
    head(p, TITLE, SUB)
    X = 36

    # --- 四级级联 ---------------------------------------------------------
    y = 146
    p.text(X, y - 30, 1300, 22,
           "<b>第一步：四级级联（时间顺序从下往上读，但根因在最下面）</b>",
           "text_b")
    stages = [
        ("④ 客户端全 500", "边侧 EngineCore 也终止，在飞请求全失败", "fail"),
        ("③ 边侧闸门死锁", "台账永不释放 → 闸门永久 HOLD → 请求不再派发", "fail"),
        ("② prefill 水位冻结", "收不完整 → 水位不推进 → prefill 停止发包", "fail"),
        ("① decode 引擎死亡", "KV 分配失败 → 抢占 → 硬编码 raise → 整个引擎退出", "cloudp"),
    ]
    for i, (name, note, role) in enumerate(stages):
        cy = y + i * 86
        p.box(X + 60, cy, 1300, 72,
              f"<b>{name}</b>　<font style=\"font-size:10px;color:#333333\">{note}</font>",
              "box", role)
    for i in range(1, len(stages)):
        cy = y + i * 86
        p.edge(src_pt=(X + 700, cy - 14), dst_pt=(X + 700, cy - 2),
               st="arrow", role="http")

    # --- 第一因 -----------------------------------------------------------
    y2 = y + 4 * 86 + 24
    p.text(X, y2 - 30, 1300, 22,
           "<b>第二步：第一因是「准入判据不完备」（一个判断少写了一部分）</b>",
           "text_b")
    p.box(X, y2, 1424, 132,
          "<font style=\"font-size:10px\">"
          "准入时问的是：<b>「这一个请求，此刻放得下吗？」</b>"
          "（单个请求 vs 当前空闲块）<br>"
          "但真正需要保证的是：<b>「所有已准入请求的需求总和，永远不超过总容量」</b><br>"
          "<font color=\"#c0392b\">前者既不包含、也不蕴含后者。</font>"
          "于是 32 个请求各自「此刻都放得下」，合起来却超过了块池——"
          "直到某一步分配失败，走到那条硬编码的「LWD 不允许抢占」断言上。<br>"
          "数量级验证：32 × 每请求块数 ≈ 块池总容量，"
          "而两侧的 <font style=\"font-size:9px\">max-num-seqs</font> 都写着 128"
          "——准入上限大约是实际可容纳并发的 <b>4 倍</b>。</font>",
          "box", "neutral")

    # --- 三个放大器 -------------------------------------------------------
    y3 = y2 + 172
    p.text(X, y3 - 30, 1300, 22,
           "<b>第三步：三个「放大器」把一个可恢复的失败放大成集群级 hang</b>",
           "text_b")
    panel(p, X, y3, 460, 190, "① 失败粒度错了", [
        "「一个请求放不下」被写成了「整个引擎退出」——",
        "硬编码 raise 让调度器的单请求失败升级为进程级 fatal。",
        "正确形态：标记该请求失败 → 交给调度器正常终结 → 引擎活着。",
    ], "fail")
    panel(p, X + 482, y3, 460, 190, "② 台账没有租约", [
        "边侧每条 chunk 都有一个「待释放」台账，只在两个时刻摘：",
        "收到首 token / 请求结束。下游死了 → 两件事都不会发生。",
        "→ 台账永久占着，闸门永久 HOLD。",
    ], "fail")
    panel(p, X + 964, y3, 460, 190, "③ 没有任何超时与死亡检测", [
        "没有对端存活检测、没有请求级超时、数据面收包只能死等。",
        "所以「等一个永远不来的东西」可以无限持续下去，",
        "表现就是「空转 680 步/秒，什么都不推进」。",
    ], "fail")

    # --- 两个反直觉证据 ---------------------------------------------------
    y4 = y3 + 230
    p.text(X, y4 - 30, 1300, 22,
           "<b>第四步：两个「看起来像正常，其实是故障指纹」的指标</b>",
           "text_b")
    rows = [
        ["running 数单调爬升、一次都没回落",
         "以为：吞吐在健康增长",
         "真相：<b>背压没生效</b>（只做了「单请求此刻够不够」的检查，没有全局账本）"],
        ["空转步数很高（edge 680、prefill 420 步/秒）",
         "以为：负载很高 / 在忙",
         "真相：在<b>等一个不会来的东西</b>，空转不是干活"],
    ]
    table(p, X, y4, [("指标形态", 460), ("第一反应", 420), ("真相", 544)], rows,
          row_h=42)

    # --- 修复 -------------------------------------------------------------
    y5 = y4 + 42 * 3 + 30
    p.box(X, y5, 1424, 132,
          "<b>第五步：修法是「让它结构上不可能发生」，而不是「让它变得可行」</b><br>"
          "<font style=\"font-size:10px\">"
          "① <b>把准入做成账本</b>：admit 即预留，校验改成「本请求需求 + 已预留总和 ≤ 总容量」"
          "→ 那条抢占断言变成<b>结构上不可达</b>。<br>"
          "② <b>把致命抢占降级为单请求失败</b>（不再 raise）。<br>"
          "③ <b>给台账加租约</b>（30 s 未释放 → 摘台账 + 请求失败）"
          "→ 任何上游单点故障都在 30 s 内变成「请求失败」而不是「集群挂住」。<br>"
          "④ <b>接上已有的恢复手段</b>：仓里那个「跳过序号」的恢复函数<b>当时根本没有调用方</b>，"
          "要接线 + 加接收超时。<br>"
          "⑤ 把并发上限由 KV 容量反推（本场景约 24~26，而不是 128）。</font>",
          "box", "cloudd")

    # --- 回归判据 ---------------------------------------------------------
    y6 = y5 + 172
    p.box(X, y6, 1424, 96,
          "<b>第六步：回归怎么判「真的好了」（三条都能自动跑）</b><br>"
          "<font style=\"font-size:10px\">"
          "① 并发曲线<b>有升有降且有上限</b>（不再单调爬），全程「导入被拒」为 0；<br>"
          "② <font style=\"font-size:9px\">kill -9</font> 掉 decode 进程，边侧应在 30 s 内把在飞请求判错，"
          "prefill 不出现无限「收不完整」；<br>"
          "③ 边侧日志里不再有「控制面投递停滞」的 fatal，只有 error + 丢弃。</font>",
          "box", "cloudp")

    y7 = y6 + 136
    bridge(p, y7, "本页交接：这是最坏形态。下一步（⑥）看一个更隐蔽的：什么都不报错，"
                  "只是显存一点点涨到 OOM。")

    y8 = y7 + 76
    anchors(p, y8, [
        "复盘原文：pds_comm_ww_边侧_decode_卡死_根因与修复.md（时序 :32-59、"
        "不变量论证 :93-102、指纹式证据 :127-130、数量级 :130、"
        "修复 P0-1…P0-5 :139-359、回归判据 :406-408）",
        "抢占即抛异常：vllm/v1/lwd_control/control_scheduler/lwd_base_scheduler.py:106",
        "准入只判「单请求 vs 当前空闲」：lwd_cloud_mixed_scheduler.py:373",
        "台账释放只有两个时刻：lwd_edge_scheduler.py（释放点与闸门逻辑）",
        "「跳过序号」恢复函数无调用方：pre_recv.py:230-236（docstring 自述）",
        "时钟不同步（边侧快约 110 s）：必须先对齐再读时序",
    ], h=120)

    y9 = y8 + 154
    concl(p, y9,
          "<b>一句话记住这个案例：</b>级联故障的根因往往只有一个「判断少写了一部分」，"
          "但被三个放大器放大成集群级事故：<b>失败粒度、台账租约、超时与死亡检测</b>。"
          "修的时候要让它结构上不可能发生，而不是让它变得可行。")

    legend(p, y9 + 92)

"""② 案例一：开了 MTP 之后，ACL 图在 26 并发静默掉出。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "② 案例一：并发爬到 26，ACL 图静默掉出——日志一个字都没说"
SUB = ("现象：压测中 25→26 并发之间，decode 步时从 <b>102 ms 跳到 145 ms</b>，"
       "再往上到 263 ms；没有任何报错、没有任何告警。"
       "根因：<b>图的上限写的是「100 个序列」，而开 MTP 后每个请求要占 4 个 token 位</b>。")


def build(doc: Doc) -> None:
    p = doc.page("② 案例：图静默掉出", pw=1560, ph=1560)
    head(p, TITLE, SUB)
    X = 36

    # --- 现象 -------------------------------------------------------------
    y = 146
    p.text(X, y - 30, 1300, 22,
           "<b>第一步：现象（全是实测数字，来自压测 10 s 窗口反算）</b>", "text_b")
    rows = [
        ["20 → 22", "80 → 88", "99 → 102 ms", "图（命中）"],
        ["25", "<b>100</b>", "102 ms", "图（<b>刚好等于上限</b>）"],
        ["<b>26</b>", "<b>104</b>", "<b>145 ms</b>", "<b>eager（掉出）</b>"],
        ["29", "116", "263 ms", "eager"],
        ["31 → 32", "124 → 128", "244 ms", "eager"],
    ]
    table(p, X, y, [("并发（序列数）", 240), ("每步 token 数", 260),
                    ("实测步时", 300), ("实际走哪条路", 620)], rows, row_h=34)
    p.box(X, y + 34 * 6 + 16, 1424, 76,
          "<font style=\"font-size:10px\">"
          "<b>关键特征：这是「拐点」，不是「斜率」。</b>"
          "20→22 只有 3 ms 的平缓增长，25→26 却突然 +42%。"
          "算力随批量增长一定是平滑的，<b>不连续跳变说明某处发生了二值判定</b>——"
          "这是本次定位的突破口。</font>",
          "box", "fail")

    # --- 阈值推导 ---------------------------------------------------------
    y2 = y + 34 * 6 + 132
    p.text(X, y2 - 30, 1300, 22,
           "<b>第二步：把阈值算出来（三步，每步都能在代码里指到）</b>", "text_b")
    p.box(X, y2, 1424, 104,
          "<font style=\"font-size:10px\">"
          "① 开 MTP 后，每个请求一步要排 <b>1 + K = 4</b> 个 token 位 → "
          "每步 token 数 = <b>4 × 序列数</b>。<br>"
          "② 图的上限是 <b>100</b>（脚本里写死的 capture_sizes 最大值）。<br>"
          "③ 所以能命中图的并发上限 = <b>100 ÷ 4 = 25</b>；"
          "第 26 个请求就让每步变成 104 个 token → <b>超过 100 → 判定 NONE → 退回 eager</b>。</font>",
          "box", "neutral")

    # --- 为什么没被发现 ---------------------------------------------------
    y3 = y2 + 144
    p.text(X, y3 - 30, 1300, 22,
           "<b>第三步：为什么从来没人发现（这段配置「曾经是死的」）</b>", "text_b")
    panel(p, X, y3, 700, 160, "三个上游缺口，全都不告警", [
        "① 框架会替你把上限「取整到 K+1 的倍数」，但<b>不会把上限本身放大</b>；",
        "② 不命中就返回 NONE，<b>没有 warning</b>；",
        "③ 唯一的不变量校验（上限 ≥ 序列数 ×(1+K)）被一个无关条件挡住，实际不生效。",
    ], "fail")
    panel(p, X + 760, y3, 664, 160, "而且它长期是「死配置」", [
        "在 P 侧与 edge 开着全局 eager 的那段时间里，这串 capture_sizes 完全不生效，",
        "所以从未被验证过。",
        "<b>它是在「同一次提交里既启用图、又开 MTP」的那一刻才变成活的</b>——",
        "一活就直接越界。",
    ], "data")

    # --- 修复 -------------------------------------------------------------
    y4 = y3 + 200
    p.text(X, y4 - 30, 1300, 22,
           "<b>第四步：修复的正确形态（不是「调大一个数」）</b>", "text_b")
    p.box(X, y4, 1424, 116,
          "<font style=\"font-size:10px\">"
          "<b>要满足一条不变量：图的最大桶 ≥ 最大并发 × (1+K)</b>，并让两个数互相兜底。<br>"
          "本案例的修法是：把并发压到 KV 撑得住的 <b>24</b>，同时把桶扩到 <b>128</b>"
          "（24 × 4 = 96 ≤ 128）→ 稳态全程命中图。<br>"
          "只扩桶不压并发：要么桶不够（继续掉出），要么 KV 撑不住（另一个坑）；"
          "只压并发不扩桶：并发上限被图卡死，与 KV 实际能力不匹配。</font>",
          "box", "cloudd")

    # --- 预防 -------------------------------------------------------------
    y5 = y4 + 156
    p.box(X, y5, 1424, 108,
          "<b>第五步：预防（这是本案例最值钱的部分）</b><br>"
          "<font style=\"font-size:10px\">"
          "① <b>启动时就打一行「图的覆盖范围」</b>：<font style=\"font-size:9px\">"
          "graph covers up to N concurrent seqs (max_capture=100, query_len=4); "
          "max_num_seqs=128 → above 25 runs eager</font> —— 有这一行，事故在拉起阶段就能发现。<br>"
          "② 把「静默回落」改成 <b>warning</b>；③ 把「模式变化」从 DEBUG 提到 INFO（只在变化时打）。</font>",
          "box", "cloudp")

    y6 = y5 + 148
    bridge(p, y6, "本页交接：这是「配置单位算错」类故障的母本。下一步（③）看它引发的连锁后果——"
                  "同样的图掉出，在压测报表上表现为「TTFT 47 秒」。")

    y7 = y6 + 76
    anchors(p, y7, [
        "复盘原文：pds_comm_ww_主因_ACL图掉出_根因与修复.md（现象 :4、步时表 :84-90、"
        "拐点论证 :92、阈值推导 :31-80、git 反查 :116-143、修复 :238-247、预防 :294-301）",
        "查询长度 = 1+K：vllm/v1/cudagraph_dispatcher.py:37-41",
        "超上限即返回 NONE（无日志）：vllm/v1/cudagraph_dispatcher.py:276-285",
        "上限自动「取整到 K+1 倍数」但不放大：vllm/config/compilation.py:1473-1518",
        "唯一可观测的模式日志：vllm-ascend/vllm_ascend/compilation/acl_graph.py:243（info_once）",
    ], h=112)

    y8 = y7 + 146
    concl(p, y8,
          "<b>一句话记住这个案例：</b>配置里的数字是<b>带单位</b>的——「100」在「1 序列 = 1 token」的"
          "世界里是 100 并发，在 MTP×4 的世界里只剩 25；"
          "<b>凡是改了前端算法（K），必须同步换算后端容量（桶、预算、槽）。</b>")

    legend(p, y8 + 92, extra_fill=("配置与容量相关", "data"))

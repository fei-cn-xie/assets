"""⑦ 案例六：多模态「挂死」——其实是被自己的核验打死的。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "⑦ 案例六：报「chunk 计划对不上」，其实是编码器缓存槽位从不归还"
SUB = ("现象：测试跑到第 33 条请求，边侧报 <code>scheduled=4 != expected=1020</code>，"
       "引擎与 API server 一起退出，客户端全 500——看起来像「服务挂死」。"
       "真相：<b>那个 4 不是预算，是聊天模板里图像占位符的下标</b>。")


def build(doc: Doc) -> None:
    p = doc.page("⑦ 案例：槽位不归还", pw=1560, ph=1560)
    head(p, TITLE, SUB)
    X = 36

    # --- 现象 -------------------------------------------------------------
    y = 146
    p.text(X, y - 30, 1300, 22,
           "<b>第一步：现象与两个「假线索」</b>", "text_b")
    p.box(X, y, 1424, 96,
          "<font style=\"font-size:10px\">"
          "报错原文：<b>chunk schedule mismatch: req=… scheduled=4 != expected=1020</b>"
          "（这是<b>边侧调度器自己的步后一致性核验</b>，不是框架报错）。<br>"
          "<b>假线索一</b>：「客户端 500 + 重试耗尽」→ 其实前 32 条是成功的，失败从第 33 条开始；"
          "<b>假线索二</b>：「云侧有告警」→ 该告警在崩溃前就已存在，且云侧还多活了 3 分多钟。</font>",
          "box", "fail")

    # --- 数字解码 ---------------------------------------------------------
    y2 = y + 136
    p.text(X, y2 - 30, 1300, 22,
           "<b>第二步：把报错里的数字「解码」（这是本案例的分水岭）</b>", "text_b")
    rows = [
        ["expected=1020", "本步计划排 1020 个 token", "picker 算出来的，正确"],
        ["scheduled=4", "<b>实际只排了 4 个</b>", "看起来像「预算被吃掉了 1016」→ <b>错</b>"],
        ["4 的真身", "<b>聊天模板里第一个图像占位符的下标</b>", "即「图像位置偏移 = 4」"],
        ["为什么是 4", "框架在「编码器缓存申请不到」时，把可排量退到「图像起点 − 已算量」",
         "计算：4 − 0 = 4"],
    ]
    table(p, X, y2, [("数字", 240), ("含义", 620), ("判断", 544)], rows, row_h=38)

    # --- 为什么申请不到 ---------------------------------------------------
    y3 = y2 + 38 * 5 + 36
    p.text(X, y3 - 30, 1300, 22,
           "<b>第三步：为什么「申请不到」——归还点被绕过了</b>", "text_b")
    p.box(X, y3, 1424, 132,
          "<font style=\"font-size:10px\">"
          "框架里，编码器缓存槽位<b>只有一个归还点</b>：一个叫「按输出更新状态」的方法。"
          "而边侧引擎<b>接管了 step</b>（自己组批、收割、投递），<b>从不调用那个方法</b>。<br>"
          "于是槽位只减不增：总量 8192，单图约 750 个嵌入 → "
          "<b>大约 10 个在飞的多模态请求就把槽位钉死</b>；此后每个新请求都走「退让到 4」这条路，"
          "撞上严格等值核验 → 引擎当场死亡。</font>",
          "box", "neutral")
    p.text(X, y3 + 142, 1424, 24,
           "<font style=\"font-size:9px;color:#666666\">"
           "这正是 ⑥ 页那个教训的另一面：接管框架的 step，等于接管它的<b>全部副作用</b>"
           "——最容易漏的就是「释放」。</font>", "subtitle")

    # --- 三种「看起来挂死」 -------------------------------------------------
    y4 = y3 + 186
    p.text(X, y4 - 30, 1300, 22,
           "<b>第四步：同一个「挂死」现象，本仓四个案例对应四种机制</b>", "text_b")
    rows2 = [
        ["进程已死", "引擎 fatal 后 API server 退出", "找 fatal 栈，不是找「卡住」"],
        ["无超时（死等）", "等一个不会来的包 / 台账不释放", "查每个等待有没有死线"],
        ["显存被钉住", "autograd 图常驻 → OOM", "查「每单位增长量」"],
        ["核验 raise", "一致性检查不等即抛", "把报错里的数字解码到业务语义"],
    ]
    table(p, X, y4, [("机制", 260), ("表现", 620), ("第一步查什么", 544)], rows2,
          row_h=34)

    # --- 修法 -------------------------------------------------------------
    y5 = y4 + 34 * 5 + 34
    p.box(X, y5, 1424, 140,
          "<b>第五步：修法的三层（缺一层都会复发）</b><br>"
          "<font style=\"font-size:10px\">"
          "① <b>补回归还</b>：按「实际执行完的量」记账并归还（不能用「乐观推进的计数」，"
          "异步流水下会提前释放仍在飞的张量）；<br>"
          "② <b>在 picker 侧预演同一套闸门</b>：申请不到就「本步不排它」，而不是排一个退让块"
          "——因为退让块的尺寸不是对齐网格的整块，推给对端会被拒收；<br>"
          "③ <b>核验保持严格，但补齐自证字段</b>（上次值/上限/缓存三项/预算/图像偏移）"
          "——失败时一眼分清「真失守」还是「资源不足」。</font>",
          "box", "cloudd")

    # --- 移植陷阱 ---------------------------------------------------------
    y6 = y5 + 180
    box_y = y6
    p.box(X, box_y, 1424, 96,
          "<b>第六步：一个特别值得记的坑——「搬旧修复前先验证前提」</b><br>"
          "<font style=\"font-size:10px\">"
          "同类崩溃在更早的分支上有过一版修复，但那份修复把「退让」当合法例外，"
          "<b>且只在「不要求前缀对齐」时才生效</b>；而本次部署恰好<b>要求对齐</b>"
          "→ 即使原样搬过来，这条崩溃路径依然会炸。</font>",
          "box", "fail")

    y7 = box_y + 136
    bridge(p, y7, "本页交接：到这里「静默」「级联」「泄漏」「核验」四类都见过了。"
                  "下一步（⑧）看最后一类最难查的——什么都不崩，只是答案错了。")

    y8 = y7 + 76
    anchors(p, y8, [
        "复盘原文：LWD_chunk_mismatch_根因分析报告.md（报错原文 :1、数字 :32-37、"
        "七项排除 :68-76）、LWD_chunk_mismatch_调用栈全景.md（栈帧 :29-43、"
        "核验实现 :119-139、grep 命令 :477-480）、pds_mma_bugfix3_多模态挂死_根因与修复.md"
        "（唯一归还点 :104-107、槽位算术 :108-109、移植陷阱 :126-129、修复 :137-167）",
        "图像位置偏移与退让公式：vllm/v1/core/sched/scheduler.py:1275-1294",
        "唯一归还点与唯一调用者：scheduler.py:1740、:1469；边侧接管 step：lwd_edge_engine.py:560-649",
        "编码器缓存判负分支：vllm/v1/core/encoder_cache_manager.py:167-172（或在 impl 中）",
    ], h=120)

    y9 = y8 + 154
    concl(p, y9,
          "<b>一句话记住这个案例：</b>报错里的数字要<b>解码到业务语义</b>（4 是模板下标，不是预算）；"
          "「挂死」必须先证伪（进程死了 / 没超时 / 显存被钉 / 核验抛了，四种机制处置完全不同）；"
          "<b>接管框架的 step，就要接管它的全部副作用。</b>")

    legend(p, y9 + 92)

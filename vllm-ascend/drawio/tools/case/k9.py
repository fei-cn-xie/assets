"""⑨ 案例八：代码缺陷——调用点还在，定义被搬丢了。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "⑨ 案例八：配置全对、脚本全对，但代码被搬坏了——「调用点还在，定义没了」"
SUB = ("现象：decode 侧一起就崩。"
       "根因：<b>分支移植时丢了一行 <code>def</code>，方法体被并进了相邻方法</b>——"
       "调用点存在、定义不存在，一调就崩。")


def build(doc: Doc) -> None:
    p = doc.page("⑨ 案例：代码缺陷", pw=1560, ph=1520)
    head(p, TITLE, SUB)
    X = 36

    # --- 长什么样 ---------------------------------------------------------
    y = 146
    p.text(X, y - 30, 1300, 22,
           "<b>第一步：这类缺陷长什么样（一行之差，形态很隐蔽）</b>", "text_b")
    p.box(X, y, 690, 150,
          "<b>正常时</b><br>"
          "<font style=\"font-size:10px\">"
          "def 方法甲(self, ...):<br>"
          "　　……甲的语句……<br>"
          "　　return<br><br>"
          "def 方法乙(self, ...):<br>"
          "　　……乙的语句……</font>",
          "box", "cloudd")
    p.box(X + 730, y, 694, 150,
          "<b>搬坏之后（少了一行 def）</b><br>"
          "<font style=\"font-size:10px\">"
          "def 方法甲(self, ...):<br>"
          "　　……甲的语句……<br>"
          "　　return<br>"
          "　　<b>……乙的语句……</b>　← 被并进甲里了<br><br>"
          "<font color=\"#c0392b\">调用方法乙的地方还在 → 一调就崩</font></font>",
          "box", "fail")

    # --- 怎么快速识别 -----------------------------------------------------
    y2 = y + 190
    p.text(X, y2 - 30, 1300, 22,
           "<b>第二步：三条命令就能定性（不需要读完整个文件）</b>", "text_b")
    p.box(X, y2, 1424, 132,
          "<font style=\"font-size:10px\">"
          "① <b>找调用点</b>：在出问题的分支上 grep「方法名（」→ 命中数应大于 0；<br>"
          "② <b>找定义</b>：同一分支上 grep「def 方法名」→ <b>命中 0 就是它</b>；<br>"
          "③ <b>对账移植前后</b>：用只读方式看两个分支的同一文件"
          "（不要切别人的工作树），对比同名方法的 def 行数——少一行就是直接证据。<br>"
          "<font color=\"#c0392b\">结论要能写成一句可复核的布尔事实：「调用点存在但定义不存在」。</font></font>",
          "box", "neutral")

    # --- 处置 -------------------------------------------------------------
    y3 = y2 + 172
    p.text(X, y3 - 30, 1300, 22,
           "<b>第三步：处置方式（这里有个「本仓不该做的事」的血泪教训）</b>",
           "text_b")
    panel(p, X, y3, 700, 172, "错误做法（本仓历史上真实发生过）", [
        "把补丁放进<b>部署配置仓</b>，并在 README 里写「必须先 git apply」。",
        "结果：被要求全部撤回。",
        "原因：一旦混入代码补丁，「跑起来的到底是哪份代码」就说不清了，",
        "而且会形成「第二份真相」被后人继续传播。",
    ], "fail")
    panel(p, X + 760, y3, 664, 172, "正确做法", [
        "只<b>报告</b>，不动手：给出六项——现象 / 根因（含归属）/ 证据（文件:行号）/",
        "影响面 / 建议改法（描述性）/ 验证方式。",
        "由代码仓的分支与 PR 去落地。",
        "部署仓只做「能不能用配置绕开」的判断与规避。",
    ], "cloudd")

    # --- 六项报告模板 -----------------------------------------------------
    y4 = y3 + 212
    p.text(X, y4 - 30, 1300, 22,
           "<b>第四步：六项报告模板（照着填，别人能复核）</b>", "text_b")
    rows = [
        ["现象", "用户看到的报错原文 + 触发条件"],
        ["根因", "一句话结论 + <b>归属判断</b>（脚本 / 配置 / 代码 / 环境）"],
        ["证据", "文件:行号；最好给出「调用点存在但定义不存在」这类布尔事实"],
        ["影响面", "谁会挂、是否必现、有没有绕开办法"],
        ["建议改法", "描述性（例如「恢复该方法的 def 行」），<b>不附可执行补丁</b>"],
        ["验证方式", "改完怎么确认（拉起、对账、跑通哪条链）"],
    ]
    table(p, X, y4, [("项", 180), ("写什么", 1244)], rows, row_h=34)

    # --- 归属判据 ---------------------------------------------------------
    y5 = y4 + 34 * 7 + 34
    p.box(X, y5, 1424, 100,
          "<b>第五步：怎么判断「这是代码问题还是配置问题」</b><br>"
          "<font style=\"font-size:10px\">"
          "① 把配置回退到已知可用的版本，问题还在 → 大概率不是配置；"
          "② 换一个分支/构建，问题消失 → 代码差异（这时用上面的三条命令去对账）；"
          "③ 问题只在某个具体输入上出现，且能用一个「不该发生」的数字复现 → 逻辑缺陷；"
          "④ <b>如果配置里有能绕开的项，就先绕开并记录</b>——但要说清「这只是规避，不是修复」。</font>",
          "box", "neutral")

    y6 = y5 + 140
    bridge(p, y6, "本页交接：8 个案例到这里。最后一步（⑩）把它们压成一张速查表 + 十条误导线索。")

    y7 = y6 + 76
    anchors(p, y7, [
        "本案例与处置规范：assets/AGENTS.md:19-33（唯一例外与同意流程）、:43-51（真实案例）、"
        ":53-66（六项报告模板）、:86-87（跨支只读比对）",
        "同一反模式的历史：曾在部署仓提交补丁目录，已 reset 撤销（AGENTS.md:48-49）",
        "「不改他人工作树」的只读手法：git show <branch>:<path> / git grep <branch>",
    ], h=104)

    y8 = y7 + 136
    concl(p, y8,
          "<b>一句话记住这个案例：</b>代码缺陷的识别只要三条命令（调用点 / 定义 / 对账），"
          "但<b>处置边界比识别更重要</b>——部署仓只报告不落补丁，"
          "否则「跑的是哪份代码」就再也说不清了。")

    legend(p, y8 + 92)

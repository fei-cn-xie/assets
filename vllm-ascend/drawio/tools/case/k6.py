"""⑥ 案例五：边侧 NPU OOM——权重只有 5.6 GB，却吃掉 59 GB。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "⑥ 案例五：边侧权重只有 5.6 GB，显存却涨到 59 GB"
SUB = ("现象：边侧 Worker OOM（<b>已分配 59.05 GiB</b>，而边侧权重只有 <b>5.6 GiB</b>）。"
       "第一反应：「跑起来本来就吃满 / 碎片化」。"
       "真相：<b>整条边侧前向跑在「开梯度」状态下，计算图被缓存钉住</b>——每张图约 1.4 GiB。")


def build(doc: Doc) -> None:
    p = doc.page("⑥ 案例：autograd 图泄漏", pw=1560, ph=1520)
    head(p, TITLE, SUB)
    X = 36

    # --- 反差数字 ---------------------------------------------------------
    y = 148
    p.text(X, y - 30, 1300, 22,
           "<b>第一步：先算三个数，判断「它该不该涨」</b>", "text_b")
    cards = [
        ("权重 5.6 GiB", "卡总容量 60.96 GiB\n起步应有 ~55 GiB 余量", "neutral"),
        ("已分配 59.05 GiB", "增长 53.4 GiB\n38 张图 → <b>约 1.4 GiB/张</b>", "fail"),
        ("KV 预分配 0", "边侧零层拓扑\n<b>没有 KV 可回收兜底</b>", "data"),
    ]
    cw = 460
    for i, (name, body, role) in enumerate(cards):
        cx = X + i * (cw + 12)
        p.box(cx, y, cw, 116, "", "box", role)
        p.text(cx + 10, y + 10, cw - 20, 24, f"<b>{name}</b>", "text_b")
        p.text(cx + 10, y + 36, cw - 20, 74,
               "<font style=\"font-size:10px\">" + body.replace("\n", "<br>") + "</font>",
               "text")

    # --- 四条排除 ---------------------------------------------------------
    y2 = y + 156
    p.text(X, y2 - 30, 1300, 22,
           "<b>第二步：把「本来就该吃满」的四种解释逐条排除（这一步才省时间）</b>",
           "text_b")
    rows = [
        ["容量本来小", "权重只 5.6 GiB、总容量 60.96 GiB", "起步就有 55 GiB 余量"],
        ["KV cache 涨的", "边侧零层拓扑，KV 规格是空集，初始化只用了 0.03 s", "根本没有 KV 预分配"],
        ["数据载荷堆积", "上行约 0.3 GiB、下行 183 批合计约 66 MiB", "比泄漏量小两个数量级"],
        ["碎片化 / 性能退化", "每步耗时全程 75~85 ms，没有随运行时长恶化", "不是打滑，是真占住了"],
    ]
    table(p, X, y2, [("假设", 260), ("反证", 720), ("结论", 424)], rows, row_h=38)

    # --- 机理链 -----------------------------------------------------------
    y3 = y2 + 38 * 5 + 36
    p.text(X, y3 - 30, 1300, 22,
           "<b>第三步：机理链（四步，每步都能在代码里指到）</b>", "text_b")
    p.box(X, y3, 1424, 132,
          "<font style=\"font-size:10px\">"
          "① 边侧 Worker <b>覆写</b>了框架的「执行一步」方法，直接调模型子模块——"
          "而<b>原方法上带着「不建计算图」的装饰器</b>，覆写后就丢了；<br>"
          "② 于是整条边侧前向跑在<b>开梯度</b>状态下：视觉塔每次前向都建一张计算图，"
          "输出张量带着「梯度追溯链」；<br>"
          "③ 这个输出被放进<b>请求级缓存</b>，而 PD 场景下这份缓存<b>到请求结束才释放</b>；<br>"
          "④ 于是<b>图 + 视觉塔全部层激活</b>被一起钉住：一张图约 1.4 GiB，"
          "35 个在飞就是 50 GiB+ → 必撞顶。</font>",
          "box", "fail")

    # --- 两个反直觉 -------------------------------------------------------
    y4 = y3 + 172
    p.text(X, y4 - 30, 1300, 22,
           "<b>第四步：两个反直觉的观察（学会能少走很多弯路）</b>", "text_b")
    panel(p, X, y4, 700, 168, "① OOM 报的位置不是元凶", [
        "报错在视觉塔内部的 attention 算子（只差 78 MiB）、",
        "两秒后又在排序算子（68 MiB）再炸一次。",
        "那是「卡已经满了、只差最后一个大分配」的<b>落点</b>，",
        "不是「这个算子要得多」。",
    ], "fail")
    panel(p, X + 760, y4, 664, 168, "② 它是被「修好上一个 bug」暴露出来的", [
        "更早的几轮里，同一个部署在 31 条请求时就先被另一个缺陷打死，",
        "来不及跑到 OOM。",
        "「上一轮的问题修好了」不等于「系统健康」——",
        "<b>它只是让下一层缺陷有机会显形</b>。",
    ], "data")

    # --- 修复 -------------------------------------------------------------
    y5 = y4 + 208
    p.box(X, y5, 1424, 100,
          "<b>第五步：修复三件套（根因 + 双保险 + 可观测性）</b><br>"
          "<font style=\"font-size:10px\">"
          "① <b>给覆写的方法补上「无梯度」上下文</b>（本案例用「不建图」而非更激进的模式，"
          "因为方法内要对锁页内存取 numpy 视图，受后者限制）；<br>"
          "② <b>写缓存前再 detach 一次</b>（双保险：即使将来有人再绕过装饰器，也不会把图带进缓存）；<br>"
          "③ <b>把内存打出来</b>：每步日志追加「已分配 / 峰值」与「缓存张量个数」——"
          "复盘里明说「这次是靠事后推算出来的，下次不该再这样」。</font>",
          "box", "cloudd")

    y6 = y5 + 140
    bridge(p, y6, "本页交接：本案例是「覆写框架方法丢了隐含契约」。下一步（⑦）是同一个教训的另一种表现——"
                  "覆写之后把「该归还的东西」忘了归还。")

    y7 = y6 + 76
    anchors(p, y7, [
        "复盘原文：pds_mma_bugfix3_第二轮_边侧NPU_OOM_根因与修复.md（OOM 头 :32-34、"
        "栈与落点 :36-42、权重与 KV :52-68、四条排除 :62-72、每图增长量 :76-79、"
        "代码链 :83-96、历史对照 :98-108、修复 :116-128、判定标准 :147-148）",
        "被覆写的方法与原方法的装饰器：lwd_edge_worker.py:194（覆写）、"
        "model_runner_v1.py:1924（@torch.inference_mode()）",
        "上游三处都没有梯度上下文：worker.py:613、worker_base.py:349、"
        "multiproc_executor.py:1214",
        "缓存与常驻：_lwd_mm_embeds_dict（请求级缓存）、"
        "lwd_edge_scheduler.py:2644（retain_mm=True）",
    ], h=128)

    y8 = y7 + 162
    concl(p, y8,
          "<b>一句话记住这个案例：</b>覆写框架方法 = 连带丢掉它的<b>隐含契约</b>"
          "（这里是「不建计算图」）；而「缓存 + 常驻」会把任何泄漏放大几十倍。"
          "<b>内存类问题先算「每单位增长量 × 单位数」，再去找是谁把它钉住了。</b>")

    legend(p, y8 + 92, extra_fill=("常驻/无 KV 兜底", "data"))

"""① 排障方法论：先分诊，再定位层，再用对照实验二分。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc

TITLE = "① 排障方法论：先分诊，再定位到「哪一层」，最后用对照实验二分"
SUB = ("一句话：本仓二十多份复盘文档反复用的其实是<b>同一套四步法</b>——"
       "分诊（是崩/挂/慢/错）→ 定位层（前端/引擎/worker/数据面/代码）→ 二分对照 → 固化成断言。"
       "本页把这套方法显式画出来，后面九页都是它的实例。")


def build(doc: Doc) -> None:
    p = doc.page("① 排障方法论", pw=1560, ph=1500)
    head(p, TITLE, SUB)
    X = 36

    # --- 四步 -------------------------------------------------------------
    y = 148
    p.text(X, y - 32, 1300, 22,
           "<b>第一步：四步法（顺序不能乱，尤其第 1 步）</b>", "text_b")
    steps = [
        ("① 分诊", "先归类：崩 / 挂 / 慢 / 错", "cloudp"),
        ("② 定位层", "确定问题落在哪一层", "cloudd"),
        ("③ 二分", "改一个变量做对照实验", "data"),
        ("④ 固化", "把结论变成断言或监控", "fail"),
    ]
    cw = 340
    for i, (name, note, role) in enumerate(steps):
        cx = X + i * (cw + 21)
        p.box(cx, y, cw, 84,
              f"<b>{name}</b><br>"
              f"<font style=\"font-size:9px;color:#666666\">{note}</font>",
              "box_center", role)
        if i:
            p.edge(src_pt=(cx - 19, y + 42), dst_pt=(cx - 3, y + 42), st="arrow",
                   role="http")

    # --- 分诊表 -----------------------------------------------------------
    y2 = y + 124
    p.text(X, y2 - 32, 1300, 22,
           "<b>第二步：分诊——先看「它怎么坏的」，四类走完全不同的路</b>", "text_b")
    from dg import table
    rows = [
        ["崩（进程退出）", "有报错栈 / 退出码非 0", "读栈顶 → 找抛错点", "案例：缺失 def、OOM"],
        ["挂（不动了）", "无报错、无输出、超时", "抓栈 / 看各进程状态", "案例：边侧 decode 卡死"],
        ["慢（性能劣化）", "能跑但指标变差", "对比 baseline，找哪一项变了", "案例：图掉出、TTFT/TPOT 劣化"],
        ["错（结果不对）", "不崩但内容/精度不对", "对拍、逐段二分", "案例：精度 63.80"],
    ]
    table(p, X, y2, [("类别", 200), ("识别特征", 340), ("第一动作", 420),
                     ("本仓实例", 464)], rows, row_h=40)

    # --- 五条原则 ---------------------------------------------------------
    y3 = y2 + 40 * 5 + 40
    p.text(X, y3 - 32, 1300, 22,
           "<b>第三步：五条贯穿所有案例的原则（都是复盘里反复出现的话）</b>",
           "text_b")
    principles = [
        ("证据优先于直觉", "先看日志/栈/指标，再猜原因；\n每一次「我觉得是……」都被复盘推翻了。"),
        ("先建立 baseline", "「变差」必须有对照：同一配置、同一负载、\n改前改后各一次。"),
        ("按侧/按层二分", "边 vs 云、P vs D、target vs draft、\n图 vs eager——一次只动一侧。"),
        ("默认不相信「配置已生效」", "开了一个开关，必须找到它生效的日志或指标；\n找不到就当作没生效。"),
        ("把结论变断言", "修完要能在下次自动发现：\n断言、校验、监控项，而不是记在脑子里。"),
    ]
    for i, (name, body) in enumerate(principles):
        cx = X + i * 288
        p.box(cx, y3, 274, 128, "", "box", "neutral")
        p.text(cx + 10, y3 + 8, 254, 22, f"<b>{name}</b>", "text_b")
        p.text(cx + 10, y3 + 32, 254, 90,
               "<font style=\"font-size:9px\">" + body.replace("\n", "<br>") + "</font>",
               "text")

    # --- 各层入口 ---------------------------------------------------------
    y4 = y3 + 168
    p.text(X, y4 - 32, 1300, 22,
           "<b>第四步：定位层——每层的「第一手证据」在哪</b>", "text_b")
    rows2 = [
        ["前端（API server）", "HTTP 状态码、SSE 是否断开、请求日志", "进程/线程 ④⑤"],
        ["EngineCore", "调度日志、engine 死亡帧、忙循环是否在转", "进程/线程 ④⑦"],
        ["worker（设备侧）", "device 报错、显存日志、图捕获日志", "图捕获 ⑦⑩"],
        ["数据面（KV/主机面）", "块校验、传输完成/超时、校验和不匹配", "Mooncake ⑦⑧"],
        ["配置层", "启动日志里的最终取值（不是你以为的值）", "组合配置 ③⑩"],
        ["代码层", "调用栈里「调用点存在但定义不匹配」", "本套 ⑨"],
    ]
    table(p, X, y4, [("层", 260), ("第一手证据", 700), ("去哪套图查机制", 464)], rows2,
          row_h=34)

    y5 = y4 + 34 * 7 + 36
    bridge(p, y5, "本页交接：方法论有了。后面九页是九个真实案例，每个都按「现象 → 排查路径 → 根因 → 修复 → 预防」走一遍。")

    y6 = y5 + 76
    anchors(p, y6, [
        "本仓复盘文档目录（根目录）：`pds_comm_ww_主因_ACL图掉出_根因与修复.md`、"
        "`pds_comm_ww_边侧_decode_卡死_根因与修复.md`、`pds_comm_ww_TTFT_TPOT_劣化分析.md`、"
        "`pds_comm_spec_decode指标全零分析.md`、`LWD_chunk_mismatch_根因分析报告.md`、"
        "`pds_mma_bugfix3_*`（多轮）",
        "「代码缺陷不在部署仓修」的约定：assets/AGENTS.md:19-33、:73-88",
        "排障命令与日志位置：见本套 ⑩ 页",
    ], h=112)

    y7 = y6 + 146
    concl(p, y7,
          "<b>一句话记住这一页：</b>先归类（崩/挂/慢/错），再定位到层，"
          "然后用「只改一个变量」的对照实验二分，最后把结论固化成断言——"
          "<b>这四个动作之后，剩下的都只是熟练度问题。</b>")

    legend(p, y7 + 92)

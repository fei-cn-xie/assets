"""⑧ 案例七：精度 63.80——分数能复现，归因仍可能是错的。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "⑧ 案例七：精度从 89 掉到 63.8，第一版归因是错的（而且分数能精确复现）"
SUB = ("现象：TextVQA 准确率 <b>63.80</b>，全程不崩、无 500、无 OOM。"
       "第一版结论：「主因是思维链吃光了输出预算」。"
       "<b>这个结论能精确复现 63.80，但它是错的</b>——真因是位置编码偏移。")


def build(doc: Doc) -> None:
    p = doc.page("⑧ 案例：精度归因", pw=1560, ph=1580)
    head(p, TITLE, SUB)
    X = 36

    # --- 三步分流 ---------------------------------------------------------
    y = 146
    p.text(X, y - 30, 1300, 22,
           "<b>第一步：精度类故障的第一件事——分流「不会算」还是「不会说」</b>",
           "text_b")
    rows = [
        ["严格判据", "63.80", "官方口径：答案需精确匹配"],
        ["放宽判据（答案含标准答案即算对）", "<b>89.00</b>", "说明<b>模型确实读到了图</b>、内容没错"],
        ["只看「没被截断」的那 80 条", "80.00（放宽后 93.75）", "说明截断确实吃掉一部分分"],
    ]
    table(p, X, y, [("口径", 400), ("分数", 220), ("它告诉你什么", 804)], rows,
          row_h=38)
    p.box(X, y + 38 * 4 + 16, 1424, 92,
          "<font style=\"font-size:10px\">"
          "<b>分流结论：81% 的题其实答到了正确内容</b> → 链路没有「算错」，"
          "于是第一版把损失全部归给「输出太长 / 被截断」。<br>"
          "<font color=\"#c0392b\">但这一步只解释了「丢分的形式」，没有解释「为什么会答偏」"
          "——这正是第一版结论错的地方。</font></font>",
          "box", "fail")

    # --- 第一版为什么错 ---------------------------------------------------
    y2 = y + 38 * 4 + 148
    p.text(X, y2 - 30, 1300, 22,
           "<b>第二步：第一版结论错在哪（这是本案例最贵的教训）</b>", "text_b")
    panel(p, X, y2, 700, 186, "第一版：主因 = 思维链 + 输出预算", [
        "证据：20 条输出没有结束标记，长度≈2046 token，正好卡在 2048 上限；",
        "放宽判据后 89 分；关掉思考模式后分数回升。",
        "<b>而且用官方评分器重放，能精确复现 63.80。</b>",
        "→ 看起来「证据链完整」。",
    ], "fail")
    panel(p, X + 760, y2, 664, 186, "它错在：把「症状」当成了「原因」", [
        "复现分数只校验了<b>评分口径</b>，没有校验<b>因果链</b>。",
        "「关掉思考」只是<b>把症状藏起来</b>：位置偏移让模型答非所问、思维链打转，",
        "关掉思考就不再打转，分数回升——但错位本身还在。",
        "<b>所以那个「修复」后来被撤销了。</b>",
    ], "fail")

    # --- 真因 -------------------------------------------------------------
    y3 = y2 + 226
    p.text(X, y3 - 30, 1300, 22,
           "<b>第三步：真因怎么找到的——去查「两侧算出的位置」是否一致</b>",
           "text_b")
    p.box(X, y3, 1424, 132,
          "<font style=\"font-size:10px\">"
          "同一批请求，P 侧与 D 侧各打一条「位置偏移」日志："
          "P 侧是 <b>−640</b>，D 侧是 <b>−1</b>；100 条请求全都同型。<br>"
          "含义：<b>生成段每个 token 的绝对位置，与 prefill 写 KV 时用的位置相差 639</b>。<br>"
          "于是模型在「位置对不上的上下文」上续写——<b>输出流畅、不报错，但系统性答非所问</b>；"
          "并且容易打转、退化（出现过 7000 字符的循环、1941 个连续同字符），"
          "最后撞上输出上限被截断。<br>"
          "<font color=\"#c0392b\">这同时解释了第一版看到的全部现象：截断、冗长、"
          "以及「答案里的词明明对」。</font></font>",
          "box", "data")

    # --- 为什么 −1 --------------------------------------------------------
    y4 = y3 + 172
    panel(p, X, y4, 1424, 130, "为什么会算出 −1（机理，一句话）", [
        "D 侧的位置表初始是「按纯文本从 0 连续排」；PD 分离下 D 侧实际只收到「尾窗」那一小段，"
        "于是按「窗口最大值」反推偏移时，<b>那些没被覆盖的初始残值（约等于 prompt 长度）占了主导</b>",
        "→ 偏移塌成 −1。修法是让 D 侧采用<b>边侧下发的整段位置最大值</b>，"
        "并按接收端 prompt 长度裁剪，避免 P 侧偏差 1。",
    ], "cloudp")

    # --- 噪声底 -----------------------------------------------------------
    y5 = y4 + 170
    p.text(X, y5 - 30, 1300, 22,
           "<b>第四步：精度类还有一个必须知道的数字——单轮噪声底 ±10</b>",
           "text_b")
    p.box(X, y5, 1424, 116,
          "<font style=\"font-size:10px\">"
          "同一批样本、温度 0、连跑 8 次：总分在 <b>46~74</b> 之间波动；"
          "<b>100 条里有 52 条出现过「这轮对、那轮错」</b>。<br>"
          "所以：① <b>单轮数字不足以判定回归</b>，要跑 3 轮取均值；"
          "② 想压低噪声得固定批形（小并发）或让边侧直接采用云侧 token（协议上刻意不做）；"
          "③ 反例也很有用：<b>加大输出预算并没有提升精度</b>——两次更大预算的运行里，"
          "截断数反而更多（25/29 条），严格精度只有 49.9/49.6。</font>",
          "box", "fail")

    y6 = y5 + 156
    bridge(p, y6, "本页交接：精度类最难的是「输出流畅且不报错」。下一步（⑨）看最后一类——"
                  "根因根本不在配置与数据面，而在代码本身被搬坏了。")

    y7 = y6 + 76
    anchors(p, y7, [
        "复盘原文：pds_mma_bugfix3_第三轮_精度63.80_归因与修复.md（三口径 :93-97、"
        "历史 8 次 :110-125、噪声底 :121-125、加大预算无效 :173-175、"
        "usage 兜底 :186-201）、pds_mma_bugfix3_第四轮_mrope_delta_根因更正与合并.md"
        "（更正判词 :26-27、:117、两侧 delta 对照 :35-39、机理 :56-58、"
        "对账指标 :97-101、修复提交 :70-81）",
        "位置退让与位置表构造：vllm/v1/core/sched/scheduler.py:1275-1294",
        "单轮噪声与固定批形的关系：见「组合配置」套 ⑤（调度平顺性）",
    ], h=120)

    y8 = y7 + 154
    concl(p, y8,
          "<b>一句话记住这个案例：</b>「分数能复现」只证明评分口径对，<b>不证明归因对</b>；"
          "精度问题要先分流「不会算 / 不会说」，再去对拍两侧的关键量（这里是位置偏移），"
          "并且永远用<b>多轮均值</b>判断回归。")

    legend(p, y8 + 92, extra_fill=("真因：两侧位置不一致", "data"))

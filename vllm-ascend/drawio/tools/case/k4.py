"""④ 案例三：指标全零——「零」有四种含义，别急着报故障。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "④ 案例三：spec_decode 指标全是零，是接受率 0% 吗？"
SUB = ("现象：<code>/metrics</code> 里 spec decode 四个计数器全是 0，但位置标签 0/1/2 都在。"
       "第一反应：「MTP 挂了」。真相：<b>「计数器为 0」至少有四种含义</b>，"
       "而其中一种是<b>正常态</b>。")


def build(doc: Doc) -> None:
    p = doc.page("④ 案例：指标全零", pw=1560, ph=1520)
    head(p, TITLE, SUB)
    X = 36

    # --- 四种零 -----------------------------------------------------------
    y = 148
    p.text(X, y - 30, 1300, 22,
           "<b>第一步：「零」的四种含义（处置完全不同）</b>", "text_b")
    rows = [
        ["① 这个角色本来就不产生", "计数器注册了、永远为 0",
         "<b>正常态</b>（P 侧只算 prefill，没有 decode 验证步）", "按角色排除告警"],
        ["② 功能压根没启动", "配置里没有投机，计数器<b>根本不注册</b>",
         "连标签都不会出现", "查配置"],
        ["③ 启动了但没走 draft", "标签在、drafts 也是 0",
         "调度器从不排 draft", "查调度与日志三条证词"],
        ["④ 走了但全被拒", "drafts &gt; 0，accepted == 0",
         "接受率真的 0%（草案太差）", "换 draft 策略"],
    ]
    table(p, X, y, [("含义", 260), ("指标形态", 400), ("解释", 420), ("处置", 344)], rows,
          row_h=40)
    p.box(X, y + 40 * 5 + 16, 1424, 76,
          "<font style=\"font-size:10px\">"
          "<b>本次实测的形态是第 ③ 种：</b>标签在（说明配置里有 K=3），"
          "但 <b>drafts 和 draft_tokens 都是 0</b>——说明计数链的<b>起点</b>就从未成立，"
          "不是「全被拒」（那样 drafts 会大于 0）。</font>",
          "box", "fail")

    # --- 判定链 -----------------------------------------------------------
    y2 = y + 40 * 5 + 132
    p.text(X, y2 - 30, 1300, 22,
           "<b>第二步：一条五跳判定链（逐个排除，每跳都有检查动作）</b>", "text_b")
    chain = [
        ("① 进程在吗", "其它计数器在涨吗"),
        ("② 角色是什么", "P / D / edge"),
        ("③ 配置有 K 吗", "看标签是否存在"),
        ("④ 调度排 draft 了吗", "看引擎内日志"),
        ("⑤ 统计送到了吗", "看是否有丢弃/异常"),
    ]
    cw = 270
    for i, (name, note) in enumerate(chain):
        cx = X + i * (cw + 11)
        p.box(cx, y2, cw, 84,
              f"<b>{name}</b><br>"
              f"<font style=\"font-size:9px;color:#666666\">{note}</font>",
              "box_center", "cloudp")
        if i:
            p.edge(src_pt=(cx - 9, y2 + 42), dst_pt=(cx - 1, y2 + 42), st="arrow",
                   role="http")

    # --- 关键判据 ---------------------------------------------------------
    y3 = y2 + 124
    p.text(X, y3 - 30, 1300, 22,
           "<b>第三步：两个关键判据（学会就能省下大量时间）</b>", "text_b")
    panel(p, X, y3, 700, 176, "判据一：「壳在」只证明构造函数跑过", [
        "位置标签来自「按 K 生成 0…K-1」，`_created` 来自对象创建时刻——",
        "两者都只依赖<b>配置</b>，不依赖<b>数据流</b>。",
        "所以「标签齐全」不能证明功能在跑。",
        "（顺带：那个 1.79e9 的大数是「创建时间戳」，不是次数——"
        "别把它读成 drafts 数。）",
    ], "fail")
    panel(p, X + 760, y3, 664, 176, "判据二：用不变量自检", [
        "健康时三个数必须同时成立：",
        "① draft_tokens ÷ drafts ≈ K；",
        "② 逐位置接受数<b>单调递减</b>（越往后越难中）；",
        "③ 逐位置之和 = 接受总数。",
        "任何一条不成立，就说明统计链或功能链有问题。",
    ], "cloudd")

    # --- P 侧正常态 -------------------------------------------------------
    y4 = y3 + 216
    p.box(X, y4, 1424, 116,
          "<b>第四步：为什么 P 侧恒零是正常的（这是最容易被误报的一条）</b><br>"
          "<font style=\"font-size:10px\">"
          "本仓的 P 侧与 D 侧<b>都带同样的投机配置</b>（K=3），所以两侧都会注册这四族指标；"
          "但 P 侧只算 prefill、没有 decode 的验证步 → "
          "「本步要验证的草案」集合长期为空 → 计数恒为 0。<br>"
          "<font color=\"#c0392b\">所以「指标名相同 + 两侧同配置」会天然制造假阳性："
          "监控面板必须<b>按角色分实例抓取</b>，否则 P 侧的恒零会污染 D 侧的接受率分母。</font></font>",
          "box", "data")

    # --- 结论与处置 -------------------------------------------------------
    y5 = y4 + 156
    p.box(X, y5, 1424, 104,
          "<b>第五步：本案例的最终结论（如实标注：文档自身留了三个候选）</b><br>"
          "<font style=\"font-size:10px\">"
          "文档给出三种可能：A 侧别正常态（P 侧）、B 前端统计链在某分支上不可靠"
          "（仓内注释自认这块薄弱）、C 进程刚起或窗口内没跑 decode 流量。"
          "并明确「数据本身定不了」，需再跑三条命令才能定案。<br>"
          "<b>这正是本案例最值得学的地方：<u>敢于把结论写成「待定」并给出定案命令</u>，"
          "而不是硬编一个根因。</b></font>",
          "box", "neutral")

    y6 = y5 + 144
    bridge(p, y6, "本页交接：这是「静默失效」类故障。下一步（⑤）看最严重的一类——"
                  "级联故障：一个请求放不下，最后整个集群挂住。")

    y7 = y6 + 76
    anchors(p, y7, [
        "复盘原文：pds_comm_spec_decode指标全零分析.md（四族指标 :4、_created 定性 :13-24、"
        "标签与配置 :27、三种解释 :35-38、判定链 :65-80、多条证词命令 :116-167、"
        "正常态对照 :181-198、恒等式自检 :194-198）",
        "「没有配置就不注册计数器」：vllm/v1/spec_decode/metrics.py:150-152",
        "位置标签按 K 生成：同文件 :181-198",
        "指标丢弃与冻结：vllm/v1/engine/async_llm.py:761-775（record 无条件、异常后冻结）",
        "前端统计链薄弱的自认注释：lwd_cloud_mixed_scheduler.py:107-115",
    ], h=120)

    y8 = y7 + 154
    concl(p, y8,
          "<b>一句话记住这个案例：</b>看到「指标为零」先问三件事——"
          "<b>这个角色该不该产生它？壳在是否等于在跑？分子为 0 还是分母为 0？</b>"
          "答案不同，处置完全相反。")

    legend(p, y8 + 92, extra_fill=("正常态，不要告警", "data"))

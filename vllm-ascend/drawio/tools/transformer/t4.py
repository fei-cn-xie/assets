"""④ 位置编码（RoPE）：模型怎么知道「谁在前、谁在后」。

RoPE 是唯一必须出现 2×2 结构的地方（它作用在坐标对上），本页会明确说明
为什么这里的小矩阵不可避免，以及它并不参与"教学矩阵乘"。
"""
from mth import (ACT, CALC, ERR, NOTE, OUT, W, arrow, legend, matrix, strip,
                 title)

TITLE = "④ 位置编码（RoPE）：给每个 token 打上「我在第几位」"
SUB = ("注意力天生「看不见顺序」——把 5 个 token 打乱，算出来的分数集合不变。"
       "RoPE 用「按位置旋转向量」的办法把顺序编码进去。动手算一遍就懂。")


def build(doc) -> None:
    p = doc.page("④ 位置编码 RoPE", pw=1700, ph=1280)
    title(p, TITLE, SUB, w=1620)

    # --- 为什么需要位置 ---------------------------------------------------
    y = 150
    p.text(36, y - 34, 1100, 22,
           "<b>第一步：先看清问题——注意力是「无序」的</b>", "text_b")
    p.box(36, y, 800, 104,
          "<b>注意力只算「token 之间的相似度」</b><br>"
          "把「我 爱 吃 苹果」里的「我」和「苹果」对调，"
          "两两相似度的<b>集合</b>完全一样——模型分不出谁先谁后。<br>"
          "<font style=\"font-size:9px\" color=\"#666666\">"
          "所以必须额外把位置信息「掺」进向量里，而不是指望注意力自己发现</font>",
          "box", ERR)
    p.box(866, y, 798, 104,
          "<b>掺法有历史演进</b><br>"
          "① 绝对位置：第 0 位加向量 p0、第 1 位加 p1…（简单，但长文本外推差）<br>"
          "② <b>RoPE（现在主流）</b>：不加法，而是<b>按位置旋转</b> Q/K 向量<br>"
          "<font style=\"font-size:9px\" color=\"#666666\">"
          "Llama / Qwen / 绝大多数开源模型都用 ②</font>",
          "box", ACT)

    # --- 配对旋转 ---------------------------------------------------------
    y2 = y + 160
    p.text(36, y2 - 34, 1200, 22,
           "<b>第二步：RoPE 的核心动作——把向量两两配对，各旋转一个角度</b>", "text_b")
    p.box(36, y2, 420, 120,
          "<b>一个 6 维向量分成 3 对</b><br>"
          "<font style=\"font-size:10px\">(x₀,x₁) &nbsp;(x₂,x₃) &nbsp;(x₄,x₅)</font><br>"
          "每一对用<b>同一个角度 θ</b> 旋转；"
          "不同对用不同频率（第 i 对的角度是 θᵢ × 位置）。<br>"
          "<font style=\"font-size:9px\" color=\"#666666\">"
          "所以「改位置」=「换一个旋转角度」，非常连续、非常好外推</font>",
          "box", NOTE)

    # 旋转公式 + 数字
    p.box(486, y2, 520, 120,
          "<b>一对坐标的旋转（这就是全部数学）</b><br>"
          "<font style=\"font-size:10px\">"
          "x' = x·cosθ − y·sinθ<br>"
          "y' = x·sinθ + y·cosθ</font><br>"
          "<font style=\"font-size:9px\" color=\"#666666\">"
          "写成矩阵就是那个 2×2 旋转块——<b>它只作用在一对坐标上，"
          "不是用来教矩阵乘的</b></font>",
          "box", CALC)

    # 数值例子表
    rowsh = [
        ["第 1 对", "(0.80, 0.60)", "0°", "(0.80, 0.60)"],
        ["第 2 对", "(0.60, -0.80)", "37°", "(0.96, 0.20)"],
        ["第 3 对", "(-0.28, 0.96)", "90°", "(-0.96, -0.28)"],
    ]
    from dg import table
    table(p, 1036, y2 - 4, [("配对", 110), ("旋转前 (x,y)", 170),
                            ("角度 θ", 90), ("旋转后 (x',y')", 170)],
          rowsh, row_h=38)
    p.text(1036, y2 + 152, 620, 40,
           "<font style=\"font-size:9px\" color=\"#666666\">"
           "cos37°≈0.80、sin37°≈0.60：正好是 3-4-5 勾股比，"
           "所以这里能写成 0.8/0.6 这种好算的数；"
           "真实模型的角度是查表得到的浮点（cos/sin 表，d/2 个频率）</font>",
           "subtitle")

    # --- 为什么只转 Q/K ---------------------------------------------------
    y3 = y2 + 220
    p.text(36, y3 - 34, 1200, 22,
           "<b>第三步：为什么只旋转 Q 和 K，不旋转 V</b>", "text_b")
    p.box(36, y3, 520, 132,
          "<b>因为位置只影响「谁该注意谁」</b><br>"
          "注意力分数 = Q·Kᵀ。把 Q、K 各自旋转 θᵢ、θⱼ 后，"
          "它们的内积只取决于<b>角度差 (θᵢ−θⱼ)</b>——也就是<b>相对距离</b>。<br>"
          "<font style=\"font-size:9px\" color=\"#666666\">"
          "这就是 RoPE 的精髓：绝对位置进入，相对距离出来</font>",
          "box", OUT)
    p.box(586, y3, 520, 132,
          "<b>V 只负责「搬内容」</b><br>"
          "V 是被加权求和的内容，它不需要知道自己的位置；"
          "旋转 V 只会白白改变输出向量的方向。<br>"
          "<font style=\"font-size:9px\" color=\"#666666\">"
          "所以实现里只对 q、k 调用 rotary_emb（见锚点）</font>",
          "box", NOTE)
    p.box(1136, y3, 528, 132,
          "<b>长文本外推：改的是「频率表」</b><br>"
          "θᵢ = 1 / (10000^(2i/d))（Llama 的 rope_theta=10000）。"
          "想支持更长上下文，就把这个底数调大（如 500000）或对角度做缩放。<br>"
          "<font style=\"font-size:9px\" color=\"#666666\">"
          "config.json 里的 rope_theta / rope_scaling 就是这个（⑮）</font>",
          "box", NOTE)

    # --- 代码锚点 --------------------------------------------------------
    y4 = y3 + 176
    p.box(36, y4, 1628, 100,
          "<b>代码锚点</b><br>"
          "<font style=\"font-size:9px\" color=\"#666666\">"
          "构建旋转表：vllm/model_executor/models/llama.py:236"
          "（_init_rotary_emb）→ :243（self.rotary_emb = get_rope(...)）<br>"
          "真正施加旋转：同文件 :231（q, k = self.rotary_emb(positions, q, k)）"
          "——注意只传了 q、k，没有 v<br>"
          "实现细节（cos/sin 表怎么按位置切片）：vllm/model_executor/layers/"
          "fused_qk_norm_rope.py 与各 attention backend 的 rope 实现"
          "</font>", "box", NOTE)

    y5 = y4 + 134
    p.box(36, y5, 1628, 74,
          "<b>这一页要记住的</b>：位置信息不是「加一个向量」，而是「按位置旋转 Q/K」；"
          "旋转后 Q·Kᵀ 只依赖角度差 → 相对距离；V 不旋转。"
          "矩阵上你只会看到 2×2 的旋转块，这是它作用的单位，不是教学用的矩阵乘。",
          "box", ERR)

    legend(p, y5 + 108)

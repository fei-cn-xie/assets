"""⑩ 多头注意力：把一个 6 维空间拆成 2 个头，各看各的，再拼回来。"""
from dg import table
from mth import (ACT, CALC, ERR, NOTE, OUT, W, arrow, legend, matrix, op,
                 panel, title)

# 5 个 token × 6 维：把它当成「d_model=6、n_heads=2、d_head=3」
X6 = [[1, 0, 2, 1, 0, 1],
      [0, 2, 1, 0, 1, 0],
      [2, 1, 0, 1, 2, 1],
      [1, 1, 2, 0, 1, 0],
      [0, 1, 1, 2, 0, 1]]

HEAD0 = [row[0:3] for row in X6]      # 前 3 维 = 头 0
HEAD1 = [row[3:6] for row in X6]      # 后 3 维 = 头 1

TITLE = "⑩ 多头注意力：拆成几份并行算，再拼回来"
SUB = ("为什么要多头？因为「一种关注方式」不够用：有的头盯语法、有的头盯指代、"
       "有的头盯标点。多头 = 把特征维切开，各自算一遍注意力，最后拼接。"
       "本页用 6 维拆成 2 个头来演示。")


def build(doc) -> None:
    p = doc.page("⑩ 多头注意力", pw=1700, ph=1340)
    title(p, TITLE, SUB, w=1620)

    # --- 形状账 -----------------------------------------------------------
    y = 150
    panel(p, 36, y, 1628, "先算清形状：多头不增加总维度，只是把一个空间切成几块",
          "d_model = 6，n_heads = 2 → d_head = 6/2 = 3。"
          "每个头各自有一份 W_Q/W_K/W_V，形状是 <b>6×3</b>（输入 6 维 → 输出 3 维）。<br>"
          "<font style=\"font-size:9px\" color=\"#666666\">"
          "真实模型：d_model=4096、n_heads=32 → d_head=128；"
          "每个头的 W 是 4096×128。两个头之间<b>不共享</b>权重。</font>",
          CALC)

    # --- 拆 ---------------------------------------------------------------
    y2 = y + 108
    p.text(36, y2 - 60, 1200, 22,
           "<b>第一步：沿特征维切开（这就是「拆头」的全部动作）</b>", "text_b")
    mx, my, _ = matrix(p, 60, y2 + 6, X6, ACT, name="X（5×6）",
                       dim="5 个 token × 6 维", cw=44)
    p.text(60, my + 12, 420, 40,
           "<font style=\"font-size:9px\" color=\"#666666\">"
           "前 3 列 → 头 0；后 3 列 → 头 1</font>", "subtitle")

    ox = op(p, mx + 16, y2 + 40, "拆", 44, 40)
    h0x, h0y, _ = matrix(p, ox + 16, y2 + 6, HEAD0, OUT, name="头 0（5×3）",
                         dim="第 0~2 维")
    h1x, h1y, _ = matrix(p, h0x + 40, y2 + 6, HEAD1, OUT, name="头 1（5×3）",
                         dim="第 3~5 维")
    p.text(h0x + 40, h1y + 12, 700, 40,
           "<font style=\"font-size:9px\" color=\"#666666\">"
           "拆完就是两份独立的 5×3，各自跑 ⑥→⑦→⑧→⑨（形状完全一样）</font>",
           "subtitle")

    # --- 每个头各自算 -----------------------------------------------------
    y3 = y2 + 210
    p.text(36, y3 - 60, 1200, 22,
           "<b>第二步：每个头内部都重复 ⑥~⑨（本页只给形状，不重复算一遍）</b>",
           "text_b")
    rows = [
        ["头 0：Q₀ = X₀·W_Q₀", "5×3 · 3×3", "5×3", "该头自己的 query"],
        ["头 0：S₀ = Q₀·K₀ᵀ", "5×3 · 3×5", "5×5", "该头自己的注意力表"],
        ["头 0：O₀ = P₀·V₀", "5×5 · 5×3", "5×3", "该头加工后的结果"],
        ["头 1：同上一整套", "同上", "5×3", "另一套完全独立的权重"],
        ["拼接 [O₀ ; O₁]", "5×3 接 5×3", "5×6", "沿特征维接回 6 维"],
        ["O = 拼接·W_O", "5×6 · 6×4", "5×4", "输出投影（可换成任意输出维）"],
    ]
    tbl = table(p, 36, y3 + 6, [("步骤", 300), ("乘法形状", 200), ("结果", 120),
                                ("含义", 300)], rows, row_h=36)

    rp = panel(p, 1100, y3 + 6, 564, "为什么必须再乘一次 W_O",
               "拼接只是「把两份结果首尾接上」，没有让两个头的信息真正混合。"
               "乘 W_O（6×4）之后，每个输出维都是两个头所有维的加权和——"
               "<b>头与头之间才发生交互</b>。<br>"
               "<font style=\"font-size:9px\" color=\"#666666\">"
               "这也是 o_proj 存在的唯一理由；省掉它，多头就等于「各自为政」。</font>",
               NOTE)

    # --- 为什么 -----------------------------------------------
    y4 = max(tbl, rp[1]) + 50
    panel(p, 36, y4, 810, "为什么多头有用（一个具体的例子）",
          "一句话里「小明把书给了小红，因为她明天要走」：<br>"
          "· 一个头可以学「代词 → 最近的女性名字」（指代消解）<br>"
          "· 另一个头可以学「动词 → 它的宾语」（语法结构）<br>"
          "· 再一个头可以学「相邻词」<br>"
          "<font style=\"font-size:9px\" color=\"#666666\">"
          "如果只有一个头，这些关系必须挤在同一张 5×5 表里互相干扰。</font>",
          NOTE)
    panel(p, 866, y4, 798, "GQA：现代模型为什么 K/V 的头数更少",
          "Llama-2 用 32 个头算 Q，但 K/V 也只有 32 份；"
          "Llama-3 / Qwen2.5 改成 <b>Q 有 32 个头，K/V 只有 8 个</b>（4 个 Q 头共用一份 K/V）。<br>"
          "原因很实在：<b>K/V 要存进 KV cache</b>，头数直接决定显存。减到 1/4，"
          "缓存就小到 1/4，而效果几乎不掉。<br>"
          "<font style=\"font-size:9px\" color=\"#666666\">"
          "config.json 里 num_attention_heads 与 num_key_value_heads 不相等就是 GQA（⑮）。</font>",
          ERR)

    # --- 代码锚点 --------------------------------------------------------
    y5 = y4 + 170
    p.box(36, y5, 1628, 100,
          "<b>代码锚点</b><br>"
          "<font style=\"font-size:9px\" color=\"#666666\">"
          "多头在实现里不是一个循环，而是<b>一个更大的矩阵乘</b>："
          "vllm/model_executor/layers/linear.py:995（QKVParallelLinear，"
          "一次算出所有头的 q/k/v，并按 TP 把头分到各卡）<br>"
          "头的切分与拼接在 attention backend 内部完成（reshape + transpose），"
          "数学上等价于本页的「拆 → 各算 → 拼」<br>"
          "头数与头维：vllm/model_executor/models/llama.py:165 附近读取 config 的 "
          "num_heads / num_kv_heads；输出投影 :175（o_proj）"
          "</font>", "box", NOTE)

    legend(p, y5 + 132)

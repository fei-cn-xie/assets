"""④ 显存账：训练四件套 vs 推理三件套。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "④ 显存账：训练要存四份东西，推理只存三份（且其中一份是「峰值」）"
SUB = ("一句话：训练显存 = <b>权重 + 梯度 + 优化器状态 + 激活</b>；"
       "推理显存 = <b>权重 + KV cache + 激活峰值</b>。"
       "前者「梯度、优化器」两份在推理里根本不存在——这就是同样一张卡推理能扛更多并发的根本原因。")


def build(doc: Doc) -> None:
    p = doc.page("④ 显存账对照", pw=1560, ph=1500)
    head(p, TITLE, SUB)
    X = 36

    # --- 对照表 -----------------------------------------------------------
    y = 148
    p.text(X, y - 32, 1300, 22,
           "<b>第一步：六项对照（右列带锚点＝本仓可查；标「通用知识」＝仓内无依据）</b>",
           "text_b")
    rows = [
        ["权重", "1× 参数量（通用知识）", "1× 参数量（仓内日志明确统计）", "两边都有"],
        ["梯度", "≈1× 参数量（通用知识）", "<b>没有</b>", "推理不反向"],
        ["优化器状态", "Adam 一阶+二阶 ≈2×，混合精度再加 1× fp32 主权重（通用知识）",
         "<b>没有</b>", "推理不更新"],
        ["激活", "要留到反向用，∝ 层数×batch×序列（通用知识）",
         "<b>只要峰值</b>，算完即释放", "推理不留账本"],
        ["KV cache", "不存在（整段并行算，不缓存）（通用知识）",
         "推理独有，随 token 线性增长", "推理独有"],
        ["经验比例", "混合精度 Adam 常按 权重:梯度:优化器 ≈ 1:1:2（通用知识）",
         "权重 + 激活峰值 + KV（仓内会计口径）", "差一个量级"],
    ]
    table(p, X, y, [("项", 150), ("训练", 520), ("推理", 460), ("结论", 294)], rows,
          row_h=42)

    # --- 推理侧的会计公式 -------------------------------------------------
    y2 = y + 42 * 7 + 40
    p.text(X, y2 - 32, 1300, 22,
           "<b>第二步：推理侧的会计口径（这是仓内真的在跑的一段代码）</b>", "text_b")
    p.box(X, y2, 1424, 108,
          "<font style=\"font-size:11px\">"
          "<b>非 KV 显存 = 权重 + 非 torch 占用 + 激活峰值 + 图显存</b><br>"
          "<b>KV 可用 = 显存上限 − 非 KV 显存 − 一小块冗余</b><br>"
          "<font style=\"font-size:10px\">"
          "日志会把这四项分开打印（权重、峰值激活、图显存各多少 GiB），"
          "所以「为什么 KV 只剩这么点」是<b>可以直接查</b>的，不用猜。</font></font>",
          "box", "neutral")

    # --- 三个推论 ---------------------------------------------------------
    y3 = y2 + 148
    p.text(X, y3 - 32, 1300, 22,
           "<b>第三步：由这张表能推出的三个实践结论</b>", "text_b")
    panel(p, X, y3, 460, 168, "① 同样一张卡，推理能扛更多并发", [
        "训练要花 3~4 倍参数量的显存在梯度与优化器上；",
        "推理把这两份全省下来 → 全部可以给 KV。",
        "这就是「部署 7B 模型单卡能跑几十并发」的算术基础。",
    ], "cloudd")
    panel(p, X + 482, y3, 460, 168, "② 训练用「重算」换显存，推理用「缓存」换算力", [
        "训练显存紧张 → 重算激活（checkpointing）、切分到多卡；",
        "推理算力闲着 → 把历史 K/V 缓存下来（KV cache），",
        "拿显存换算力——两者方向相反，因为瓶颈不同。",
    ], "cloudp")
    panel(p, X + 964, y3, 460, 168, "③ 推理多了「激活峰值」这个必须量的东西", [
        "训练不需要精确知道激活峰值（反正都要存）；",
        "推理必须先空跑一遍量出峰值，才能算出「还剩多少给 KV」。",
        "→ 这就是启动时那次 profile_run 存在的唯一理由。",
    ], "fail")

    # --- 一句话端口 -------------------------------------------------------
    y4 = y3 + 208
    p.box(X, y4, 1424, 96,
          "<b>一句话把训练与推理的显存哲学分开</b><br>"
          "<font style=\"font-size:10px\">"
          "训练：<b>显存换正确性</b>——存下中间结果，才能算梯度、才能更新。<br>"
          "推理：<b>显存换并发</b>——不存梯度，改成存 KV，让更多请求同时在跑。<br>"
          "于是同一份权重，在两种场景下的「最优显存布局」完全相反。</font>",
          "box", "cloudd")

    y5 = y4 + 136
    bridge(p, y5, "本页交接：四项里最容易被低估的是「激活」。"
                  "下一步（⑤）专门讲它——包括一个从 288 MB 涨到 6 GB 的真实算术。")

    y6 = y5 + 76
    anchors(p, y6, [
        "推理的会计口径（非 KV = 权重+非torch+激活峰值+图）："
        "vllm/v1/worker/gpu_worker.py:850-854；日志文案 :873-877",
        "加权算例（权重 2 GiB + 激活峰值 2 GiB + 非 torch 1 GiB）："
        "vllm/utils/mem_utils.py:242-273",
        "推理只用推理模式（不建梯度图）：vllm/v1/worker/gpu/model_runner.py:773 等 "
        "@torch.inference_mode()",
        "「vLLM 是推理专用、没有反向」的原文："
        "vllm/third_party/flash_linear_attention/ops/layernorm_guard.py:514-516",
        "训练侧四项系数与 1:1:2 比例：通用知识（仓内无依据）",
    ], h=112)

    y7 = y6 + 146
    concl(p, y7,
          "<b>一句话记住这一页：</b>训练显存 = 权重 + 梯度 + 优化器 + 激活账本；"
          "推理显存 = 权重 + KV + 激活峰值。"
          "<b>少掉的是「为了更新参数而付的钱」，多出来的是「为了服务并发而付的钱」。</b>")

    legend(p, y7 + 92, extra_fill=("推理独有 / 可利用", "cloudd"))

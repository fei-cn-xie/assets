"""⑥ 精度：bf16 / fp16 / fp32，以及那个专为「训练-推理一致性」存在的 fp32 头。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "⑥ 精度：推理为什么能整份用 bf16，而训练必须留一份高精度"
SUB = ("一句话：训练要更新参数，所以需要<b>高精度的主权重</b>来累积微小变化；"
       "推理只读不写，整份用 bf16 就够——只有 logits 这一步被特意提到 fp32，"
       "因为<b>它要和训练侧算出的概率对齐</b>。")


def build(doc: Doc) -> None:
    p = doc.page("⑥ 精度", pw=1560, ph=1480)
    head(p, TITLE, SUB)
    X = 36

    # --- 三种精度 ---------------------------------------------------------
    y = 150
    p.text(X, y - 32, 1300, 22,
           "<b>第一步：三种精度的取舍（训练 vs 推理）</b>", "text_b")
    rows = [
        ["fp32", "4 字节，范围和精度都够", "主权重、优化器状态、logits",
         "太占显存与带宽，不用于主体计算"],
        ["bf16", "2 字节，范围大、尾数少", "训练与推理的默认计算精度",
         "精度略低但很少溢出"],
        ["fp16", "2 字节，尾数比 bf16 多、范围小", "老模型 / 部分推理场景",
         "<b>容易溢出</b>，某些模型仓内直接建议别用"],
        ["int8 / fp8", "1 字节", "量化推理（见 ⑦）", "需要量化产物，不能直接训练"],
    ]
    table(p, X, y, [("精度", 130), ("特点", 420), ("谁在用", 420), ("注意", 454)],
          rows, row_h=40)

    # --- 仓内的规则 -------------------------------------------------------
    y2 = y + 40 * 5 + 40
    p.text(X, y2 - 32, 1300, 22,
           "<b>第二步：仓内 dtype 的四条规则（都是自动的，不需要你操心）</b>",
           "text_b")
    panel(p, X, y2, 700, 168, "① auto 的含义", [
        "看到 fp32/fp16 的模型 → 用 fp16；看到 bf16 的模型 → 用 bf16。",
        "也就是说「权重文件里是什么精度，我就用什么精度跑」。",
    ], "neutral")
    panel(p, X + 760, y2, 664, 168, "② 哪些转换允许、哪些只警告", [
        "升精度（fp32 上采）允许并打 info；",
        "降精度到 fp16/bf16 也允许；",
        "<b>fp16 ↔ bf16 互转只给 warning</b>——因为两者都「合法」但可能改变数值行为。",
    ], "cloudp")

    y3 = y2 + 208
    panel(p, X, y3, 700, 148, "③ 有些模型被写死「别用 fp16」", [
        "仓内有一张名单（gemma2 / gemma3 / glm4 等），",
        "注释直接写「数值不稳定，请用 bf16 或 fp32」。",
        "原因：fp16 的动态范围小，这些模型的激活容易溢出。",
    ], "fail")
    panel(p, X + 760, y3, 664, 148, "④ KV cache 有它自己的精度旋钮", [
        "KV cache 可以用更低精度存（例如 fp8），与权重精度<b>分开配置</b>。",
        "这是推理独有的优化：KV 占显存大头，压它收益最大。",
        "（量化细节见 ⑦；本仓只有一个包显式用了 indexer 侧的 int8）",
    ], "cloudd")

    # --- fp32 头 ----------------------------------------------------------
    y4 = y3 + 188
    p.box(X, y4, 1424, 130,
          "<b>第三步：那个「专门为训练-推理一致性存在的 fp32 头」（本仓注释原话）</b><br>"
          "<font style=\"font-size:10px\">"
          "lm_head 默认跟着主体精度；但仓内提供了把<b>输出头单独提到 fp32</b> 的开关，"
          "注释写明：<font style=\"font-size:9px\">an fp32 head is required for RL training-inference "
          "consistency</font>。<br>"
          "为什么：强化学习用推理引擎算 log 概率作为训练信号，如果推理侧的概率与训练侧算出来的不一致，"
          "训练就会被带偏 → 所以把这一步算到 fp32 并保持两侧一致。<br>"
          "<font color=\"#c0392b\">这是本套图里「训练与推理必须数值对齐」的唯一硬证据。</font></font>",
          "box", "cloudp")

    y5 = y4 + 170
    bridge(p, y5, "本页交接：精度讲完。下一步（⑦）进入量化——它是「整份用低精度」这条路的极端版本，"
                  "也是本仓唯一一个有真实部署配置的精度话题。")

    y6 = y5 + 76
    anchors(p, y6, [
        "dtype 配置与 auto 语义：vllm/config/model.py:170-179",
        "字符串→dtype 映射：vllm/config/model.py:2238-2244；合法取值 :100",
        "转换规则（升/降/互转只警告）：vllm/config/model.py:2355-2364",
        "fp16 不稳定模型名单：vllm/config/model.py:2251-2257（_FLOAT16_NOT_SUPPORTED_MODELS）",
        "fp32 头与训练-推理一致性（原文）：vllm/model_executor/layers/logits_processor.py:92-96；"
        "实现 :163-170",
        "KV cache 精度（推理独有）：vllm/config/cache.py:111-120、取值域 :39-58",
        "训练侧主权重 / loss scaling：通用知识（仓内无实现）",
    ], h=128)

    y7 = y6 + 162
    concl(p, y7,
          "<b>一句话记住这一页：</b>训练要留高精度主权重是为了「能累积微小更新」，"
          "推理整份低精度是因为「只读不写」；"
          "<b>唯一被特意提回 fp32 的是输出头——因为要跟训练侧的概率对齐。</b>")

    legend(p, y7 + 92)

"""⑩ 真实接口：vLLM 作为强化学习的 rollout 后端。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "⑩ 真实接口：训练框架把 vLLM 当成「会改权重的推理后端」"
SUB = ("一句话：强化学习需要「<b>用当前策略采样 → 训练 → 更新策略 → 再采样</b>」，"
       "而采样这一步就是推理。于是 vLLM 提供了<b>权重同步、暂停/继续、逐层热更新、休眠让卡</b>"
       "这些为训练准备的能力——这是训练与推理唯一真实的耦合面。")


def build(doc: Doc) -> None:
    p = doc.page("⑩ RL 后端接口", pw=1560, ph=1560)
    head(p, TITLE, SUB)
    X = 36

    # --- 循环 -------------------------------------------------------------
    y = 148
    p.text(X, y - 32, 1300, 22,
           "<b>第一步：RL 训练的一个回合（vLLM 在「采样」这一格）</b>", "text_b")
    loop = [
        ("① 采样", "用当前权重跑推理，生成回答并记录概率", "cloudd"),
        ("② 打分", "奖励模型 / 规则给每个回答打分", "neutral"),
        ("③ 训练", "按优势算策略梯度，更新权重", "cloudp"),
        ("④ 同步", "把新权重推给正在服务的推理引擎", "fail"),
        ("⑤ 回到 ①", "下一回合用新权重继续采样", "neutral"),
    ]
    cw = 274
    for i, (name, note, role) in enumerate(loop):
        cx = X + i * (cw + 11)
        p.box(cx, y, cw, 92,
              f"<b>{name}</b><br>"
              f"<font style=\"font-size:9px;color:#666666\">{note}</font>",
              "box_center", role)
        if i:
            p.edge(src_pt=(cx - 9, y + 46), dst_pt=(cx - 1, y + 46), st="arrow",
                   role="http")

    # --- 四个能力 ---------------------------------------------------------
    y2 = y + 132
    p.text(X, y2 - 32, 1300, 22,
           "<b>第二步：为此 vLLM 提供了四件东西（都在仓里能查到）</b>", "text_b")
    panel(p, X, y2, 460, 196, "① 权重同步通道", [
        "训练进程侧有一个「发送端」引擎，推理侧有一个「接收端」；",
        "中间可以走 NCCL、共享内存、分片传输等多种后端。",
        "还配了一组 HTTP 控制路由（暂停采样 / 初始化 / 开始更新 / 结束）。",
    ], "cloudp")
    panel(p, X + 482, y2, 460, 196, "② 暂停 / 继续", [
        "更新权重时不能让引擎正在生成 → 先暂停（把在跑的请求收尾），",
        "更新完再继续。这样训练与推理可以共用同一批卡。",
    ], "cloudd")
    panel(p, X + 964, y2, 460, 196, "③ 逐层热更新", [
        "更细的做法：按层加载新权重，不重启引擎。",
        "并且<b>保持张量地址不变</b>——否则已捕获的图会失效（图捕获 ④ 的约束二）。",
        "代价：更新期间该层算出的结果可能新旧混用，所以必须暂停。",
    ], "fail")

    # --- 两个「让卡」的能力 -----------------------------------------------
    y3 = y2 + 236
    p.text(X, y3 - 32, 1300, 22,
           "<b>第三步：两个很容易被忽略、但对 RL 很关键的能力</b>", "text_b")
    panel(p, X, y3, 700, 170, "休眠（让出显存给训练）", [
        "训练要占大量显存（梯度+优化器），与推理抢卡；",
        "所以推理引擎支持「睡下去」把显存还回去，训练完再「醒来」。",
        "可以只回权重（保留 KV 结构）或全放。",
    ], "data")
    panel(p, X + 760, y3, 664, 170, "采样掩码 / 路由复现（一致性）", [
        "RL 要保证「推理时算的概率」与「训练时假设的概率」一致：",
        "① 把 top-k/top-p 实际保留下来的词集合返回给训练侧；",
        "② 把 MoE 的路由选择也返回；",
        "③ 输出头用 fp32 算（⑥ 页那条）——三者都是为同一件事。",
    ], "cloudd")

    # --- 一张对照：谁在做 -------------------------------------------------
    y4 = y3 + 210
    p.text(X, y4 - 32, 1300, 22,
           "<b>第四步：这条链上「谁负责什么」（避免把它们当成同一个东西）</b>",
           "text_b")
    rows = [
        ["训练框架（verl / TRL / OpenRLHF …）", "算策略梯度、决定权重怎么变", "仓外"],
        ["训练进程侧的同步客户端", "把新权重推过去、发暂停/更新指令", "<b>仓内</b>（不在训练循环里）"],
        ["vLLM 引擎", "用当前权重采样、返回概率与统计", "<b>仓内</b>"],
        ["训练脚本", "决定 K、温度、批次等采样参数", "仓外"],
    ]
    table(p, X, y4, [("角色", 520), ("职责", 520), ("在哪", 384)], rows, row_h=36)

    y5 = y4 + 36 * 5 + 34
    p.box(X, y5, 1424, 96,
          "<b>三句话总结本套</b><br>"
          "<font style=\"font-size:10px\">"
          "① <b>训练</b>：靠梯度改权重，显存花在梯度/优化器/激活上，产出 checkpoint。<br>"
          "② <b>推理</b>：只读权重，显存花在 KV 上，靠调度/图/量化/投机把每个 token 变便宜。<br>"
          "③ <b>两者的接口只有三处</b>：权重文件（含量化描述）、配置字段（训练期字段被忽略）、"
          "以及 RL 场景下的运行时权重同步。<font color=\"#c0392b\">除此之外它们几乎不重叠——"
          "这就是为什么读 vLLM 时找不到训练代码，却处处能看到「为训练准备」的开关。</font></font>",
          "box", "neutral")

    y6 = y5 + 136
    bridge(p, y6, "本页交接：训练侧到此闭合。回到 `学习地图.md`，这一套应插在"
                  "「Transformer 与模型文件结构」之后、「入门」之前读——"
                  "它解释的是「权重从哪来」，而入门套解释的是「系统为什么这么设计」。")

    y7 = y6 + 76
    anchors(p, y7, [
        "权重同步配置（文档串明写 RL training）：vllm/config/weight_transfer.py:8-15",
        "训练侧引擎「跑在训练进程里」：vllm/distributed/weight_transfer/base.py:554-583",
        "推理侧引擎与初始化时机：同文件 :465-479、:528-535",
        "四种同步后端注册表：vllm/distributed/weight_transfer/factory.py:244-266",
        "RLHF HTTP 控制路由（暂停/初始化/开始/结束/更新）："
        "vllm/entrypoints/serve/dev/rlhf/api_router.py:29、:157、:175、:187、:205",
        "「给 RL 训练用」的推理开关："
        "vllm/config/model.py:1965-1978（head_dtype fp32，原文 required for RL training-inference "
        "consistency）、:250-253（return_sampling_mask / routed_experts）",
        "休眠/唤醒：vllm/docs/features/sleep_mode.md:3、:60-64",
        "仓内 verl 的痕迹：vllm/distributed/parallel_state.py:2075-2077（注释提到 verl integration）",
        "训练生态清单：vllm/docs/training/rlhf.md:5-17",
    ], h=152)

    y8 = y7 + 186
    concl(p, y8,
          "<b>一句话记住这一页：</b>训练与推理的运行时接口只在 RL 场景显形——"
          "「采样用 vLLM，训练完把权重同步回来」；"
          "<b>那套同步/暂停/热更新/休眠的代码就在 vLLM 仓里，但它本身仍然不是训练框架。</b>")

    legend(p, y8 + 92, extra_fill=("运行时同步/权重更新", "fail"))

"""⑤ 算术强度：为什么 decode 卡在带宽上（把「瓶颈」算成数）。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "⑤ 算术强度：一个数就能判断「这一步卡在算力还是带宽」"
SUB = ("一句话：<b>算术强度 = 计算量 ÷ 访存量</b>（每读一个字节，做了多少次运算）。"
       "硬件有两个上限：算力峰值与带宽峰值；谁的「上限线」先被撞到，谁就是瓶颈。")


def build(doc: Doc) -> None:
    p = doc.page("⑤ 算术强度", pw=1560, ph=1440)
    head(p, TITLE, SUB)
    X = 36

    # --- 定义 -------------------------------------------------------------
    y = 152
    p.text(X, y - 34, 1200, 22,
           "<b>第一步：先立一个能算的数</b>", "text_b")
    p.box(X, y, 1424, 96,
          "<font style=\"font-size:11px\">"
          "<b>算术强度（arithmetic intensity）= 浮点运算次数 FLOPs ÷ 搬运字节数 Bytes</b>"
          "　　单位：FLOP / Byte<br><br>"
          "<font style=\"font-size:10px\">"
          "直觉：每从显存搬 1 个字节出来，能顺手做多少次乘加。"
          "搬得越「值」，就越可能被算力卡住；搬得越「不值」，就越容易被带宽卡住。</font></font>",
          "box", "neutral")

    # --- 硬件的两条线 -----------------------------------------------------
    y2 = y + 130
    p.text(X, y2 - 34, 1200, 22,
           "<b>第二步：硬件有两条「上限线」，谁先撞上谁是瓶颈</b>", "text_b")
    panel(p, X, y2, 700, 168, "算力上限线", [
        "算力峰值是固定的（比如每秒 X 次浮点运算）。",
        "要把算力用满，就得让「每字节带来的运算次数」足够高。",
        "算术强度高的负载 → 卡在算力（compute-bound）。",
        "典型：大矩阵乘（prefill 的宽矩阵）。",
    ], "cloudp")
    panel(p, X + 760, y2, 664, 168, "带宽上限线", [
        "带宽峰值也是固定的（每秒能搬 Y 字节）。",
        "如果每字节只做很少的运算，算力根本用不上，先撞带宽。",
        "算术强度低的负载 → 卡在带宽（memory-bound）。",
        "典型：decode —— 每步都要把全部权重读一遍，却只算 1 个 token。",
    ], "cloudd")

    # --- 用 decode 算一遍 -------------------------------------------------
    y3 = y2 + 208
    p.text(X, y3 - 34, 1300, 22,
           "<b>第三步：拿 decode 真算一遍（用相对量级，不做绝对性能承诺）</b>",
           "text_b")
    rows = [
        ["一次矩阵乘的运算量", "2 × 参数量（每个参数一次乘一次加）",
         "权重 7B → 约 1.4×10¹⁰ 次"],
        ["一次矩阵乘的访存量", "参数量的字节数（每个权重都要从显存读出来）",
         "7B × 2 字节（bf16）≈ 1.4×10¹⁰ 字节"],
        ["所以算术强度", "≈ 2 FLOP / 字节（与参数量无关！）",
         "<b>几乎恒等于 2</b>"],
        ["硬件比值", "算力峰值 ÷ 带宽峰值（常见量级：数百）",
         "远大于 2"],
        ["结论", "每字节只换 2 次运算，远低于硬件能「喂饱」的比例",
         "→ decode 必然是带宽瓶颈"],
    ]
    table(p, X, y3, [("项", 300), ("怎么算", 620), ("本例", 480)], rows, row_h=36)

    # --- 由此解释三件事 ---------------------------------------------------
    y4 = y3 + 36 * 6 + 36
    p.text(X, y4 - 34, 1300, 22,
           "<b>第四步：这个数一算出来，三件事立刻有了理由</b>", "text_b")
    panel(p, X, y4, 460, 152, "① 为什么要 batching", [
        "把 N 个请求的 decode 合成一批：",
        "运算量 ×N，访存量几乎不变（权重只读一遍）→",
        "算术强度从 2 涨到 2N → 才可能用满算力。",
    ], "neutral")
    panel(p, X + 482, y4, 460, 152, "② 为什么要量化", [
        "把权重从 2 字节压到 1 字节：",
        "访存量直接减半 → 带宽瓶颈下速度接近翻倍；",
        "代价是精度与反量化开销。",
    ], "fail")
    panel(p, X + 964, y4, 460, 152, "③ 为什么要图捕获 / PD 分离", [
        "带宽已经吃满、算力还闲着 → 那就削减「等 CPU 提交」的时间（图捕获）；",
        "或者干脆把 decode 单独放一拨机器，让「带宽密集」和「算力密集」各用各的卡。",
    ], "data")

    y5 = y4 + 192
    bridge(p, y5, "本页交接：「batching 提高算术强度」是推理系统里最重要的一条因果。"
                  "下一步（⑥）看现实中的 batching 到底难在哪（为什么需要「连续批处理」）。")

    y6 = y5 + 76
    p.box(X, y6, 1424, 76,
          "<b>说明（避免误用）</b>：<font style=\"font-size:10px\">"
          "上面的「≈2 FLOP/字节」「算力带宽比数百」是<b>量级估算</b>，用于判断瓶颈方向，"
          "不是性能承诺；真实数值取决于硬件型号、精度、算子实现与 batch 结构。"
          "本仓里也有「每张图固定驱动开销 ≥1 MiB」这类经验常量，同样只用于估算。</font>",
          "box", "fail")

    y7 = y6 + 110
    anchors(p, y7, [
        "decode 每请求 1 个 query：vllm/config/vllm.py:661-679",
        "batching 的上限由调度参数决定：vllm/config/scheduler.py:49（max_num_batched_tokens）、"
        "vllm/v1/core/sched/scheduler.py:124-130（max_num_seqs / 预算）",
        "量化入口（模型配置里的 quantization）：vllm/config/model.py（quantization 字段）",
        "图捕获的动机（削减 host 下发）：见「vLLM图捕获」套页 ①",
    ], h=96)

    y8 = y7 + 128
    concl(p, y8,
          "<b>一句话记住这一页：</b>decode 的算术强度 ≈ 2 FLOP/字节，远低于硬件算力带宽比，"
          "所以它被带宽卡死；而 batching 是唯一能<b>在不增加访存的前提下增加运算</b>的手段——"
          "这就是推理系统一切复杂度的源头。")

    legend(p, y8 + 92)

"""② 训练 vs 推理：五个必须分清的差别（表 + 后果）。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "② 训练 vs 推理：五个差别，每一个都解释了一条推理优化"
SUB = ("一句话：训练关心「算得准不准」，推理关心「答得快不快、便宜不便宜」。"
       "五个差别各自都会逼出 vLLM 里的一个设计。")


def build(doc: Doc) -> None:
    p = doc.page("② 训练 vs 推理", pw=1560, ph=1420)
    head(p, TITLE, SUB)
    X = 36

    y = 152
    p.text(X, y - 34, 1200, 22,
           "<b>第一步：一张对照表（左列是训练的习惯，右列是推理的现实）</b>",
           "text_b")
    rows = [
        ["要不要梯度", "要（存激活 + 反向传播）", "不要（算完就丢）",
         "推理显存只剩权重 + KV"],
        ["权重角色", "变量，每步都在变", "常量，加载后只读",
         "可以放心地做「格式重排」「图捕获」"],
        ["batch 的意义", "越大越好：梯度更稳、算力更满", "是吞吐与延迟的权衡",
         "连续批处理 / 调度器（⑨ ⑯ 页）"],
        ["精度", "混合精度 + fp32 主权重", "常常整份 bf16/fp16（甚至量化）",
         "量化、GGUF（Transformer ⑳）"],
        ["显存构成", "权重 + 梯度 + 优化器 + 激活", "权重 + KV cache + 激活峰值 + 图池",
         "显存账（⑦）与 KV 管理（生命周期 ⑤）"],
    ]
    table(p, X, y, [("维度", 220), ("训练时", 460), ("推理时", 420),
                    ("逼出的 vLLM 设计", 320)], rows, row_h=40)

    # --- 五条后果 ---------------------------------------------------------
    y2 = y + 40 * 6 + 40
    p.text(X, y2 - 34, 1200, 22,
           "<b>第二步：五条后果，逐条说清「所以在推理里能做什么」</b>", "text_b")
    panel(p, X, y2, 700, 132, "① 没有反向 → 显存全给「并存」", [
        "训练时 batch 大到放不下就 OOM；推理时省下的那份显存直接变成"
        "「能同时服务多少请求」。",
        "所以推理系统的核心指标之一是<b>并发</b>，而不是 batch 大小。",
    ], "cloudd")
    panel(p, X + 760, y2, 664, 132, "② 权重只读 → 可以做「静态优化」", [
        "既然是常量，就能提前把布局换好（如昇腾的 ND→NZ）、"
        "把前向录成图（图捕获那套）。",
        "训练时权重每步都变，这些优化全都不成立。",
    ], "cloudp")

    y3 = y2 + 172
    panel(p, X, y3, 700, 132, "③ batch 变成权衡 → 需要调度器", [
        "把多个请求「拼成一批」能提高吞吐，但会让某些请求等更久。",
        "于是必须有人决定「这一步算谁、算几个 token」——这就是 Scheduler。",
    ], "neutral")
    panel(p, X + 760, y3, 664, 132, "④ 精度可以降 → 省钱但可能掉点", [
        "bf16/fp16 是常态；fp8/int8 量化能把权重和 KV 都压小，",
        "代价是精度损失与额外的反量化开销——要不要用是个工程权衡。",
    ], "fail")

    y4 = y3 + 172
    panel(p, X, y4, 1424, 116, "⑤ 显存构成变了 → KV cache 成为主角", [
        "训练时激活是显存大户；推理时激活只需「一步的峰值」，"
        "而 <b>KV cache 会随「并发数 × 上下文长度」线性增长</b>，成为主要变量。",
        "所以推理系统的显存管理几乎都在管 KV：分块、复用前缀、跨机搬运、超时释放"
        "（分别对应生命周期 ⑤、Mooncake、PD 分离）。",
    ], "data")

    y5 = y4 + 156
    bridge(p, y5, "本页交接：这张表解释了「为什么要有一套推理系统」。"
                  "下一步（③）先把权重从文件搬进显存——这是 vLLM 启动时做的第一件大事。")

    y6 = y5 + 76
    anchors(p, y6, [
        "KV 块默认 16 token 一块：vllm/config/cache.py:71（DEFAULT_BLOCK_SIZE）",
        "显存利用率上限（推理专用旋钮）：vllm/config/cache.py:103"
        "（gpu_memory_utilization 默认 0.92）",
        "「只有权重+激活峰值，没有梯度」的代码证据：vllm/v1/worker/gpu_worker.py:528-642"
        "（determine_available_memory 只扣权重与激活）",
        "调度器存在的原因：vllm/v1/core/sched/scheduler.py:568（每步挑一批）",
    ], h=96)

    y7 = y6 + 128
    concl(p, y7,
          "<b>一句话记住这一页：</b>训练的取舍围着「准」转，推理的取舍围着「快和便宜」转；"
          "五个差别（梯度 / 权重角色 / batch 意义 / 精度 / 显存构成）"
          "分别逼出了调度、KV 管理、量化、图捕获这些机制。")

    legend(p, y7 + 92)

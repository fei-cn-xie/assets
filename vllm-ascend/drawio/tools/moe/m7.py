        ["EPLB 与 ModelRunner 版本", "昇腾上只有 v2 runner 支持上游 EPLB", "拒绝/降级"],
        ["量化 MoE + 动态 EPLB", "部分组合不支持（如 LoRA、per-expert 张量列表）", "拒绝"],

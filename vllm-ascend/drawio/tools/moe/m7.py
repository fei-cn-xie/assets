"""⑦ 负载均衡：训练靠损失/偏置，推理靠换位与冗余副本（EPLB）。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "⑦ 负载均衡：为什么总有「热门专家」，以及两种治它的办法"
SUB = ("一句话：路由是「谁分高谁上」，于是热门专家会越来越热、冷门专家越来越闲；"
       "<b>训练期</b>用辅助损失或路由偏置压制，<b>推理期</b>用「把专家搬/复制到空闲卡」（EPLB）削峰。")



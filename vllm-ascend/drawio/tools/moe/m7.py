        "balancedness 定义 vllm/docs/serving/expert_parallel_deployment.md:154",
        "冗余专家显存公式与 ≈2.4 GB（DeepSeek-V3）：expert_parallel_deployment.md:184-189",
        "EPLB 策略实现（含冗余专家部署）：vllm-ascend/.../eplb/core/policy/policy_default_eplb.py:298",
        "昇腾限制（同步 EPLB 不支持、弹性 EP 不兼容、需 gloo/hixl、只 MRv2）："

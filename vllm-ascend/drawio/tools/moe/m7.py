          "① <b>辅助损失</b>：训练期改梯度，从源头让分布均匀；"
          "② <b>路由偏置</b>：训练期改分数，同样从源头；"
          "③ <b>EPLB</b>：推理期搬位置/加副本，<b>不改模型、只改放置</b>；"
          "④ <b>容量因子 / token drop</b>：训练期概念，本仓推理路径<b>不做截断</b>"

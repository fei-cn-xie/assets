"""③ 矩阵乘一族：dense linear / 量化 linear / 分组矩阵乘。"""
from common import head, concl, anchors, legend, panel, bridge
from dg import Doc, table

TITLE = "③ 矩阵乘一族：三种写法，一条分派链"
SUB = ("一句话：模型里 90% 的浮点运算都是矩阵乘，而昇腾上它分成<b>三类</b>——"
       "普通线性、量化线性、以及 MoE 的分组矩阵乘；选哪一类由「权重怎么存」决定。")


def build(doc: Doc) -> None:
    p = doc.page("③ 矩阵乘家族", pw=1560, ph=1540)
    head(p, TITLE, SUB)
    X = 36

    # --- 三类 -------------------------------------------------------------
    y = 148
    p.text(X, y - 30, 1300, 22,
           "<b>第一步：三类矩阵乘（一眼分清）</b>", "text_b")
    panel(p, X, y, 460, 190, "① 普通线性（权重是 bf16）", [
        "落到最基础的矩阵乘实现，权重是「分形格式（NZ）」布局。",
        "为什么是 NZ：昇腾的矩阵算子对分形布局更友好，",
        "所以权重在<b>加载时</b>就被就地重排成 NZ（站 0 ⑧ 讲过重排的代价）。",
    ], "cloudd")
    panel(p, X + 482, y, 460, 190, "② 量化线性（权重是 int8/fp8/…）", [
        "先对激活做量化（逐 token 动态量化），",
        "再调<b>量化矩阵乘算子</b>，反量化在算子内部完成。",
        "不同量化方案对应不同算子入口（见下表）。",
    ], "cloudd")
    panel(p, X + 964, y, 460, 190, "③ 分组矩阵乘（MoE）", [
        "一次调用里为<b>每个专家各算一段 GEMM</b>（各段 M/N/K 不同）。",
        "还能进一步融合「激活 + 量化」进同一个算子。",
        "这是 MoE 套 ②⑧ 讲的那条主链的核心算子。",
    ], "cloudp")

    # --- 分派链 -----------------------------------------------------------
    y2 = y + 230
    p.text(X, y2 - 30, 1300, 22,
           "<b>第二步：量化线性的分派（按「权重怎么存」选算子）</b>", "text_b")
    rows = [
        ["W8A8（静态 / 动态）", "激活 per-token 动态量化 + 量化矩阵乘", "最常用"],
        ["W8A8 + MXFP8", "块级 FP8 尺度 + 量化矩阵乘", "更省、依赖硬件"],
        ["W4A8 / W4A4 系列", "4bit 权重 + 8/4bit 激活", "权重更小"],
        ["W8A16", "只量化权重、激活保持 bf16", "专用批矩阵乘算子"],
        ["原生块 FP8", "多数情况委托给 MXFP8 路径，否则回落普通线性", "需要转换"],
        ["MoE 的全部（w8a8/w4a8/…）", "统一走分组矩阵乘（可融合 SwiGLU + 量化）", "见 ⑧ 页"],
    ]
    table(p, X, y2, [("权重形态", 420), ("落到哪个算子", 620), ("备注", 384)], rows,
          row_h=34)

    # --- 三个细节 ---------------------------------------------------------
    y3 = y2 + 34 * 7 + 32
    p.text(X, y3 - 30, 1300, 22,
           "<b>第三步：三个容易被忽略的细节</b>", "text_b")
    panel(p, X, y3, 700, 160, "① 权重布局是加载时定的，不是算时定的", [
        "同样的算子，权重在 NZ 布局下比在普通布局下更高效；",
        "所以「加载时那一次重排」（首次约十几秒）是值得的。",
        "推论：如果你改了权重处理方式却没让它保持 NZ，性能会莫名变差。",
    ], "data")
    panel(p, X + 760, y3, 664, 160, "② 算子内部会自动处理 bias", [
        "有 bias 时量化算子内部直接加；",
        "但有些量化组合踩过 bias 相关的坑（仓内注释提过 fp8 加 bias 的缺陷），",
        "所以代码里可能为了绕开而改走别的路径。",
    ], "fail")

    y4 = y3 + 200
    p.box(X, y4, 1424, 108,
          "<b>③ 没有「按形状自动切 GEMV/GEMM」这种魔法（本仓实测结论）</b><br>"
          "<font style=\"font-size:10px\">"
          "很多人以为「小 batch 自动用向量乘、大 batch 自动用矩阵乘」。"
          "本仓代码里<b>没有这种分派</b>——分派只看「权重怎么存」（量化与否）与并行配置。<br>"
          "唯一接近「按形状选路」的地方是<b>融合通信</b>那条链："
          "按「本次有没有 prefill 请求、dtype、K 的范围、数据量是否小于 16 MB」"
          "决定「GEMM+通信融合」还是「分步 GEMM 再通信」。<br>"
          "<font color=\"#c0392b\">这个结论有用：排障时不要去找「形状分派表」，它不存在。</font></font>",
          "box", "neutral")

    y5 = y4 + 148
    bridge(p, y5, "本页交接：矩阵乘讲完。下一步（④）看剩下的「小而碎」的算子——"
                  "归一化、激活、位置编码，它们最容易被融合，也最容易回退。")

    y6 = y5 + 76
    anchors(p, y6, [
        "普通线性：vllm-ascend/vllm_ascend/ops/linear.py:139（apply 入口）、:49-54"
        "（unquantized_gemm 实现 = F.linear）、:107-123（加载时转 NZ）",
        "量化线性统一分派：quantization/method_adapters.py:209-224（AscendLinearMethod.apply）",
        "W8A8 动态：quantization/methods/w8a8/w8a8_dynamic.py:117（激活量化）、:124（量化矩阵乘）",
        "W8A8 静态：w8a8_static.py:127；MXFP8：w8a8_mxfp8.py:150；W8A16：wna16/w8a16.py:65；"
        "W4 系列：w4a8_mxfp4.py:107、w4a4_mxfp4.py:149 等",
        "MoE 分组矩阵乘：w8a8_dynamic.py:445/513/533（各段 GEMM）、"
        "device/device_op.py:349（融合 SwiGLU+量化的 NZ 变体）、:1319（v2 融合）",
        "「按形状选路」的真实位置：ops/linear_op.py:229-260（_can_fuse：按阶段/dtype/K/字节数）",
        "fp8 + bias 的已知缺陷注释：w8a8/w8a8fp8_dynamic.py:70",
    ], h=144)

    y7 = y6 + 178
    concl(p, y7,
          "<b>一句话记住这一页：</b>矩阵乘分三类——普通线性（NZ 权重）、量化线性（量化算子内反量化）、"
          "MoE 分组矩阵乘（一次调用算多段）；<b>选哪类只由「权重怎么存」决定，没有形状魔法。</b>")

    legend(p, y7 + 92, extra_fill=("MoE 分组计算", "cloudp"))
